def blob(relative, as_json=True):
    path = BASE + relative
    assert not path.endswith((".npz", ".npy", ".zip"))
    content = subprocess.check_output(["git", "show", f"{COMMIT}:{path}"], cwd=REPO)
    oid = hashlib.sha1(b"blob " + str(len(content)).encode() + b"\0" + content).hexdigest()
    PROVENANCE[path] = {
        "git_blob_oid": oid,
        "sha256": hashlib.sha256(content).hexdigest(),
        "bytes": len(content),
        "restored_to_worktree": False,
    }
    return json.loads(content) if as_json else content.decode()


def mean(values):
    return float(np.mean(list(values)))


def correlation(xs, ys):
    x, y = np.asarray(xs, dtype=float), np.asarray(ys, dtype=float)
    if x.std() < 1e-14 or y.std() < 1e-14:
        return {"pearson_r": None, "reason": "zero within-group variance", "n_worlds": len(x)}
    return {"pearson_r": float(np.corrcoef(x, y)[0, 1]), "n_worlds": len(x)}


def validate_summary_scalar(name, actual, expected):
    assert abs(actual - expected) < 1e-12, (name, actual, expected)


