def batch_tensor(items):
    """exp45.batch_tensor: inputs x, targets y and the mask of the answer positions; a shorter row is filled with the start symbol."""
    rows = [p + t for p, t in items]; L = max(len(r) for r in rows) + 1
    data = np.full((len(rows), L), BOS, dtype=np.int64)
    for i, r in enumerate(rows):
        data[i, 1:len(r) + 1] = r
    x, y = data[:, :-1], data[:, 1:]; mask = np.zeros(y.shape, bool)
    for i, (p, t) in enumerate(items):
        mask[i, len(p):len(p) + len(t)] = True
    return x, y, mask


# ---------------------------------------------------------------- the network (from the brief's terms and its two added lines)
def sigmoid(x):
    return 0.5 * (1.0 + np.tanh(0.5 * x))


class Net:
    """The brief's network: a byte table (258 by 8), l1 (8 to H) with tanh, a GRU of U cells in torch's form
    (r = s(Wir x + Whr h), z = s(Wiz x + Whz h), n = tanh(Win x + r * (Whn h)), h' = (1 - z) n + z h, rows ordered r, z, n,
    the state zero at the start of every item), and the readout z2 = tanh(l2 z1 + lm h) followed by l3.
    The two added lines of the keyed forward: on an item whose first byte x[:, 1] is a byte in use, z of cells 128.. is set to 1
    and units 256.. of z2 are set to 0.  `shut_all` sets z of cells 128.. to 1 on every item (the receipts' second scoring of the
    new task).  `off_all` sets units 256.. of z2 to 0 on every item; it is the reader's own and is used in part 8 only."""

    def __init__(self, W, dtype=np.float64):
        self.W = W = {k: np.asarray(v, dtype) for k, v in W.items()}
        self.U, self.H = W["rnn.weight_hh_l0"].shape[1], W["l1.weight"].shape[0]
        self.code = np.tanh(W["book.weight"] @ W["l1.weight"].T + W["l1.bias"])            # z1 of each of the 258 symbols
        self.gi = self.code @ W["rnn.weight_ih_l0"].T + W["rnn.bias_ih_l0"]                 # the input map's output for each symbol
        self.a2 = self.code @ W["l2.weight"].T + W["l2.bias"]                               # l2 z1 for each symbol
        self.WhT, self.bh = np.ascontiguousarray(W["rnn.weight_hh_l0"].T), W["rnn.bias_hh_l0"]
        self.lmT, self.l3T = np.ascontiguousarray(W["lm.weight"].T), np.ascontiguousarray(W["l3.weight"].T)

    def masks(self, first, in_use=None, shut_all=False, off_all=False):
        used = in_use[first] if in_use is not None else np.zeros(len(first), bool)
        shut = (used | shut_all)[:, None] & (np.arange(self.U) >= U0)[None, :]
        off = (used | off_all)[:, None] & (np.arange(self.H) >= H0)[None, :]
        return (shut if shut.any() else None), (off if off.any() else None)

    def step(self, h, byte, shut):
        U = self.U; gi = self.gi[byte]; gh = h @ self.WhT + self.bh
        r = sigmoid(gi[:, :U] + gh[:, :U]); z = sigmoid(gi[:, U:2 * U] + gh[:, U:2 * U])
        if shut is not None:
            z = np.where(shut, 1.0, z).astype(z.dtype)                                      # added line 1
        n = np.tanh(gi[:, 2 * U:] + r * gh[:, 2 * U:])
        return (1 - z) * n + z * h, z

    def readout(self, h, byte, off):
        z2 = np.tanh(self.a2[byte] + h @ self.lmT + self.W["lm.bias"])
        if off is not None:
            z2 = np.where(off, 0.0, z2).astype(z2.dtype)                                    # added line 2
        return z2 @ self.l3T + self.W["l3.bias"], z2

    def run(self, x, n_out=3, keep=False, **key):
        """One batch of rows of equal length.  Returns the outputs at the last n_out positions (rows, n_out, 257) and, with keep,
        the states after every step, the gates z and z2 at the last n_out positions."""
        shut, off = self.masks(x[:, 1], **key)
        h = np.zeros((len(x), self.U), self.gi.dtype); L = x.shape[1]; out, hs, zs, z2s = [], [], [], []
        for t in range(L):
            h, z = self.step(h, x[:, t], shut)
            if keep:
                hs.append(h); zs.append(z)
            if t >= L - n_out:
                lg, z2 = self.readout(h, x[:, t], off); out.append(lg)
                if keep:
                    z2s.append(z2)
        return np.stack(out, 1), (dict(h=np.stack(hs, 1), z=np.stack(zs, 1), z2=np.stack(z2s, 1)) if keep else None)


def groups_of(items, chunk=4096):
    g = {}
    for i, (p, a) in enumerate(items):
        g.setdefault(len(p) + len(a), []).append(i)
    for idx in g.values():
        for j in range(0, len(idx), chunk):
            yield idx[j:j + chunk]


def answer_logits(net, items, **key):
    """Outputs at the three answer positions under teacher forcing with the right answer (x = [start] + prompt + answer[:-1]),
    item by item, rows grouped by length so that none is padded."""
    out = np.empty((len(items), 3, 257))
    for idx in groups_of(items):
        out[idx] = net.run(np.array([[BOS] + items[i][0] + items[i][1][:-1] for i in idx]), **key)[0]
    return out


def generate(net, items, cap=6, **key):
    """exp11_cell.respond as read: the prompt after the start symbol, then the byte of the largest output is appended, up to
    `cap` bytes or the end symbol.  The state is carried from one step to the next, which gives the same values as running
    the lengthened row again."""
    out = [None] * len(items); g = {}
    for i, (p, _) in enumerate(items):
        g.setdefault(len(p), []).append(i)
    for idx0 in g.values():
        for j in range(0, len(idx0), 4096):
            idx = idx0[j:j + 4096]
            x = np.array([[BOS] + items[i][0] for i in idx]); shut, off = net.masks(x[:, 1], **key)
            h = np.zeros((len(x), net.U), net.gi.dtype)
            for t in range(x.shape[1]):
                h, _ = net.step(h, x[:, t], shut)
            last = x[:, -1]; gen = [[] for _ in idx]; done = np.zeros(len(idx), bool)
            for _ in range(cap):
                y = net.readout(h, last, off)[0].argmax(1)
                for q in np.nonzero(~done)[0]:
                    gen[q].append(int(y[q]))
                done |= y == EOS
                if done.all():
                    break
                h, _ = net.step(h, y, shut); last = y
            for q, i in enumerate(idx):
                out[i] = gen[q]
    return out


def exact(outs, items):
    return sum(o == t for o, (_, t) in zip(outs, items))


def score_first_family(net, S1, HELD, **key):
    """E43's scores 1 and 2 with the generated bytes kept."""
    gens = {"k0_" + n: generate(net, S1[n][0], **key) for n in S1}
    gens.update({"k12_" + n: generate(net, HELD[n], **key) for n in HELD})
    res = {}
    for n, (items, red, _) in S1.items():
        ok = [o == t for o, (_, t) in zip(gens["k0_" + n], items)]
        if n in ("add89", "sub89"):
            res[n + " reduction"] = (sum(o for o, f in zip(ok, red) if f), sum(red)); res[n + " other"] = (sum(o for o, f in zip(ok, red) if not f), len(red) - sum(red))
        else:
            res[n + " all"] = (sum(ok), len(ok))
    res["reduction_score"] = (100 * res["add89 reduction"][0] / res["add89 reduction"][1] + 100 * res["sub89 reduction"][0] / res["sub89 reduction"][1]) / 2
    for n in HELD:
        res["held " + n] = (exact(gens["k12_" + n], HELD[n]), len(HELD[n]))
    return res, gens


