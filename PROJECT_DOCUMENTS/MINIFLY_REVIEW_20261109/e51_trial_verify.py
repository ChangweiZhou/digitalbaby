def show(path, ref=WREF):
    return subprocess.run(["git", "show", f"{ref}:{path}"], capture_output=True, check=True).stdout


def load(path, ref=WREF):
    """A torch.save file as {name: numpy array}, and the SHA-256 of the file."""
    blob = show(path, ref)
    return {n.lstrip("/"): np.frombuffer(raw, dtype=DTYPE[st]).reshape(shape).copy() for n, (st, shape, raw) in tensors(blob).items()}, hashlib.sha256(blob).hexdigest()


def tensors_sha(W):
    """exp20_reference.tensors_sha, as read: for each name in sorted order, the name, torch's dtype string, the shape, the values."""
    h = hashlib.sha256()
    for k in sorted(W):
        v = W[k]
        h.update(k.encode()); h.update(b"torch.float32" if v.dtype == np.float32 else b"torch.float64"); h.update(str(tuple(v.shape)).encode()); h.update(v.tobytes())
    return h.hexdigest()


