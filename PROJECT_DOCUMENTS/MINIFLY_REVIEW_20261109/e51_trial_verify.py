def wrong_class(g, target, a, b, op):
    """The brief's classes of a wrong answer on a reduction pair, tried in its order."""
    if g == [EOS]:
        return 0
    if any(v >= 128 and v != EOS for v in g):
        return 1
    if len(g) == 3 and g[2] == EOS and all(48 <= v <= 57 for v in g[:2]):
        val, right = int(bytes(g[:2])), int(bytes(target[:2]))
        return 2 if val == apply(op, 97, a, b) else 3 if abs(val - right) in (1, 10) else 4
    return 5


