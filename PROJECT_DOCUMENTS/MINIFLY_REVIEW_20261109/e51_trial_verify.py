def first_learned(curve):
    """The brief's *learned*: the first scored row at which the score is at 80% or more with every later row also at 80% or more."""
    for i in range(len(curve)):
        if all(v >= 80 for _, v in curve[i:]):
            return curve[i][0]
    return None


def first_at_80(curve):
    """Another reading, for comparison only: the first scored row at 80% or more, whatever follows."""
    return next((u for u, v in curve if v >= 80), None)


