def later_records(ev, V, q):
    """D8 and D10's records of the reviewer's part J, with the number of earlier visits (two readings) and the first update's items."""
    W = World(1); sched = W.schedule(V)
    times, stays, last = {}, {}, {}
    out = []
    lv = {r["visit"]: r for r in q["later_visits"]}
    for v, g in enumerate(sched):
        if v in lv:
            r = dict(lv[v]); r["earlier_visits"] = times[g]; r["earlier_stays"] = stays[g]
            out.append(r)
        if g in last and last[g] == v - 1:
            pass
        else:
            stays[g] = stays.get(g, 0) + 1
        times[g] = times.get(g, 0) + 1; last[g] = v
    return out


def quantities(arm, V, ev=None, la=None):
    p = SCR / f"q_{arm}_{V}.pkl"
    if p.exists():
        return pickle.loads(p.read_bytes())
    ev = ev if ev is not None else gnpz(LIVES + STEMS[arm] + ".npz")
    q = C.l2_quantities(ev, V)
    W = World(1)
    # D6 at the first visits: the joint fit and the medians
    lev = [r["level"] for r in q["first_visits"]]
    ln_n = [math.log(r["n"]) for r in q["first_visits"]]
    tp = [len(W.taught[4 * r["family"]]) for r in q["first_visits"]]
    X = np.stack([np.ones(len(lev)), ln_n, np.log(tp)], 1)
    co = np.linalg.lstsq(X, np.asarray(lev), rcond=None)[0]
    q["joint"] = dict(ln_n=float(co[1]), ln_taught_pairs=float(co[2]))
    q["median_first"] = float(np.median(lev)); q["median_first_2_on"] = float(np.median(lev[1:]))
    q["taught_pairs"] = tp
    q["later"] = later_records(ev, V, q)
    q["kinds"] = {k: q["kind"].count(k) for k in ("first", "continuation", "return")}
    qq = V - max(1, V // 4)
    q["late_visits_by_kind"] = {k: sum(1 for v in range(qq, V) if q["kind"][v] == k) for k in ("first", "continuation", "return")}
    q["mean_512_1023"] = float(np.mean(q["score_by_age"][512:1024])) if V == 1024 else None
    blocks = []
    for b in range(0, V, 64):
        vs = range(b, b + 64)
        m = lambda xs, k=None: tmean([xs[v] for v in vs if k is None or q["kind"][v] == k])
        blocks.append(dict(visits=f"{b} to {b + 63}", all=m(q["score_by_age"]), blind=m(q["blind_by_age"]), returns=m(q["score_by_age"], "return"),
                           n_first=sum(q["kind"][v] == "first" for v in vs), n_cont=sum(q["kind"][v] == "continuation" for v in vs),
                           n_return=sum(q["kind"][v] == "return" for v in vs)))
    q["blocks"] = blocks
    p.write_bytes(pickle.dumps(q))
    return q


