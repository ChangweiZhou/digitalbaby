    seen_x = np.zeros(n_ask, np.uint32); blind_x = np.zeros(n_ask, np.uint8); mirror_x = np.zeros(n_ask, np.uint8); wrap_x = np.zeros(n_ask, np.uint8)
    seen = [0] * len(W.task); last_t = [None] * len(W.task)
    life = hashlib.sha256(); bad = []; k = 0
    for v, f in enumerate(sched):
        hv = hashlib.sha256()
        for taught, asked in W.visit(v, f):
            for i, a, b, p, y in asked:
                task[k] = i; A[k] = a; B[k] = b; tgt[k] = (y[0] - 48) * 10 + (y[1] - 48)
