def same(label, mine, theirs, tol=5e-9):
    """Compare a figure with the worker's; record and print a difference."""
    if mine is None or theirs is None:
        ok = mine is None and theirs is None
    elif isinstance(mine, (int, np.integer)) and isinstance(theirs, (int, np.integer)):
        ok = int(mine) == int(theirs)
    else:
        ok = abs(float(mine) - float(theirs)) <= tol
