def pool_d15(arm, V):
    out = {}
    for name, _, _ in ABS:
        out[name] = {}
        for en, _, _ in EARLIER:
            cs = [R[arm, w, V]["d15"][name][en] for w in WORLDS]
            items = sum(c["items"] for c in cs); right = sum(c["right"] for c in cs); visits = sum(c["visits"] for c in cs)
            f16 = sum(c["first16"] * c["visits"] for c in cs if c["visits"]) / visits if visits else None
            out[name][en] = dict(visits=visits, items=items, right=right, share=right / items if items else None, first16=f16)
    return out


def pool_d14(arm, V, kind):
    out = {}
    for name, _, _ in ABS[:4]:
        cs = [R[arm, w, V][f"d14_{kind}"][name] for w in WORLDS]
        n = sum(c["answers"] for c in cs)
        out[name] = dict(answers=n, shares={o: sum(c["shares"][o] * c["answers"] for c in cs) / n for o in ORDER},
                         chance=sum(c["chance"] * c["answers"] for c in cs) / n)
    return out


