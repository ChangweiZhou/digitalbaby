def three(curve, key, thr):
    v = [(r["step"], r[key]) for r in curve if r["step"] > 0]
    for i in range(len(v) - 2):
        if all(x[1] >= thr for x in v[i:i + 3]):
            return v[i][0]
    return None


def single(curve, key, thr):
    for r in curve:
        if r["step"] > 0 and r[key] >= thr:
            return r["step"]
    return None


