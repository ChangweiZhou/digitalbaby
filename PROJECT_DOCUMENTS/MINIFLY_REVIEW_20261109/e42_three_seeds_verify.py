def describe(x_ref, x_new, d_ref, d_new):
    """E41's four cases, read as fewer / more / about the same (candidate against reference)."""
    if x_ref and x_new:
        q = x_new / x_ref
        return "fewer" if q < 2 / 3 else "more" if q > 1.5 else "about the same"
    if x_ref and not x_new:
        return "more" if d_new / x_ref >= 1.5 else "not decided"
    if not x_ref and x_new:
        return "fewer" if x_new / d_ref <= 2 / 3 else "not decided"
    return "neither reaches"


def one(new, ref, measure, version="three"):
    """The description of one comparison on one seed, and the two values (reference, candidate)."""
    a, b = TAB[new], TAB[ref]
    if measure == "length at 40":
        d = a["len40"] - b["len40"]
        return ("lower" if d <= -15 else "higher" if d >= 15 else "about the same"), (round(b["len40"], 2), round(a["len40"], 2))
    key = f"{measure[0]}80_{version}"
    D = a["dose"] - (512 if version == "three" else 0)
    if measure.endswith("updates"):
        return describe(b[key], a[key], D, D), (b[key], a[key])
    wa, wb = (a[key] or 0) * 64 * a["wc"], (b[key] or 0) * 64 * b["wc"]
    return describe(wb or None, wa or None, D * 64 * b["wc"], D * 64 * a["wc"]), (wb, wa)


