HEAD = 8 * 512 + 512 * 512 + 512 * 257                  # l1, l2 and l3: not proportional to the number of cells
RATE = {"1": 1.0, "4": (128 + 64 / 2 + 64 / 4) / 256, "8": (128 + 64 / 2 + 32 / 4 + 32 / 8) / 256, "16": (128 + 64 / 2 + 32 / 4 + 16 / 8 + 16 / 16) / 256}
SLOW = {"1": 0, "4": 128, "8": 128, "16": 128}           # cells of period above 1


def madds(cfg):
    """Forward multiply-adds per item and position that the wiring of the brief needs (not what the masked dense code spends)."""
    rc = receipt(cfg, "S", SEEDS[0]); N, ps, var = rc["N"], rc["period_set"], rc["variant"]
    cellwork = 3 * 512 + 3 * (N + 1)                     # a cell's input map and its reading of N cells and of itself, three gates
    if var == "last":
        cells = U * cellwork * RATE[ps]                  # only the last step of a period is read: the work falls at the cell's updates
    else:
        cells = U * cellwork + 6 * SLOW[ps]              # every step of a period enters the sum, each times its weight a (three gates, two sums)
    return HEAD + 512 * U + cells                        # `lm`: every readout unit reads every cell at every position


