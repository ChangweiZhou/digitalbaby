class Saved:
    """The structure a weights file holds, in the form the reader's forward takes."""

    def __init__(self, T, variant):
        self.p, self.f, self.mask = T["periods"].astype(int), T["phases"].astype(int), T["mask"].astype(bool)
        self.K, self.variant = int(self.p.max()), variant
        self.a, self.Wx = T.get("a"), T.get("Wx")

    def mask3(self):
        return np.tile(self.mask, (3, 1))


def respond(W, S, prompts, cap=4):
    """exp11_cell.respond: greedy, one byte at a time, at most `cap` bytes, stopping at the end symbol."""
    x = np.array([[BOS] + p for p in prompts], dtype=np.int64)
    gen, done = [[] for _ in prompts], [False] * len(prompts)
    for _ in range(cap):
        yy = R.forward(W, S, x, form="afactor")[1][:, -1].argmax(1)
        for q in range(len(prompts)):
            if not done[q]:
                gen[q].append(int(yy[q]))
                done[q] = int(yy[q]) == EOS
        x = np.concatenate([x, yy[:, None]], 1)
        if all(done):
            break
    return gen


