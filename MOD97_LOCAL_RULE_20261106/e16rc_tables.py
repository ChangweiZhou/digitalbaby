"""E16-RC tables: capacity curve of the raw-byte reservoir on the standing seeds.

Reads exp45/e16_life_T_raw{16384,32768,65536,131072}_<seed>.json, the every-entry arm
exp45/e16_life_T_all_balanced_<seed>.json and the twin exp45/e16_life_D_<seed>.json, and writes
exp45/SUMMARY_E16RC.md. Reads only; changes no receipt. Missing or partial receipts are marked.

Measures (as summarize_exp16 and the E16 reports): mod-97 / mod-73 operations = mean exact accuracy at k = 12 over
the family's four operations; held compositions = mean final-answer accuracy over the four held pairs (not "within").
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
SEEDS = (73129, 93683, 116089)
CAPS = (16384, 32768, 65536, 131072)
F1 = ("add97", "sub97", "max97", "min97")
F3 = ("add73", "sub73", "max73", "min73")
HELD = ("+-", "-+", "><", "<>")


def load(name):
    p = OUT / name
    return json.loads(p.read_text()) if p.exists() else None


def ops(sc, fam):
    return 100 * sum(sc[n]["12"]["exact"] / sc[n]["12"]["n"] for n in fam) / len(fam)


def comp(sc):
    c = sc["compose"]
    return 100 * sum(c[h]["final"] / c[h]["n"] for h in HELD) / len(HELD)


def stage(r, i):
    return r["stages"][i] if r and len(r["stages"]) > i else None


def f(x, d=1):
    return "—" if x is None else f"{x:.{d}f}"


def main():
    lines = ["# SUMMARY_E16RC: capacity curve of the raw-byte reservoir (standing seeds)", "",
             "Generated by `e16rc_tables.py` from the receipts in `exp45/`. Operations: mean exact accuracy at k = 12 over the family's four operations. "
             "Compositions: mean final-answer accuracy over the four held pairs. Ratios are to the twin (`e16_life_D_<seed>.json`) after block 6. "
             "Reservoir columns are read at block 5 (after F3.1). Comp loss = held compositions after block 4 minus after block 6.", ""]
    rows = []
    for seed in SEEDS:
        D = load(f"e16_life_D_{seed}.json")
        d6 = stage(D, 6)["scores"]
        tw = dict(f1=ops(d6, F1), comp=comp(d6), f3=ops(d6, F3))
        arms = [(f"raw {c:,}", f"e16_life_T_raw{c}_{seed}.json", c) for c in CAPS] + [("every entry (E16-D)", f"e16_life_T_all_balanced_{seed}.json", None)]
        lines += [f"## Seed {seed}", "",
                  "| Arm | blocks | distinct @5 | comp. strings @5 | bytes @5 | bytes/slot | mod-97 ops @6 | held comp @6 | mod-73 ops @6 | ratio mod-97 | ratio comp | ratio mod-73 | comp @4 | comp loss 4→6 | CPU s |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for label, fn, cap in arms:
            r = load(fn)
            if r is None:
                lines.append(f"| {label} | not run | | | | | | | | | | | | | |"); continue
            nb = len(r["stages"]) - 1
            s5, s4, s6 = stage(r, 5), stage(r, 4), stage(r, 6)
            dist = s5.get("reservoir_distinct", {}).get("all") if s5 else None
            cstr = s5.get("reservoir_by_family", {}).get("F2") if s5 else None
            byt = s5.get("reservoir_bytes") if s5 else None
            slots = s5["buffer"]["all"] if (s5 and isinstance(s5.get("buffer"), dict) and "all" in s5["buffer"]) else None
            if s6:
                v = dict(f1=ops(s6["scores"], F1), comp=comp(s6["scores"]), f3=ops(s6["scores"], F3))
            else:
                v = dict(f1=None, comp=None, f3=None)
            c4 = comp(s4["scores"]) if s4 else None
            loss = (c4 - v["comp"]) if (c4 is not None and v["comp"] is not None) else None
            rat = {k: (v[k] / tw[k] if v[k] is not None else None) for k in v}
            cpu = r["stages"][-1].get("cpu")
            lines.append(f"| {label} | {nb} | {dist if dist is not None else '—'} | {cstr if cstr is not None else '—'} | {byt if byt is not None else '—'} | "
                         f"{f(byt / slots, 2) if (byt and slots) else '—'} | {f(v['f1'])} | {f(v['comp'])} | {f(v['f3'])} | {f(rat['f1'], 3)} | {f(rat['comp'], 3)} | {f(rat['f3'], 3)} | "
                         f"{f(c4)} | {f(loss)} | {f(cpu, 0)} |")
            rows.append((seed, label, cap, v, rat, loss, dist, cstr, byt, slots))
        lines.append(f"| twin (D) | {len(D['stages']) - 1} | | | | | {f(tw['f1'])} | {f(tw['comp'])} | {f(tw['f3'])} | | | | {f(comp(stage(D, 4)['scores']))} | {f(comp(stage(D, 4)['scores']) - tw['comp'])} | {f(D['stages'][-1].get('cpu'), 0)} |")
        lines.append("")
    lines += ["## Curve across seeds (held compositions after block 6 / ratio to twin)", "",
              "| Capacity | " + " | ".join(str(s) for s in SEEDS) + " |", "|---|" + "---:|" * len(SEEDS)]
    for c in CAPS + (None,):
        cells = []
        for s in SEEDS:
            m = [x for x in rows if x[0] == s and x[2] == c and (c is not None or x[1].startswith("every"))]
            cells.append(f"{f(m[0][3]['comp'])} / {f(m[0][4]['comp'], 3)}" if m and m[0][3]["comp"] is not None else "—")
        lines.append(f"| {'every entry' if c is None else f'{c:,}'} | " + " | ".join(cells) + " |")
    lines.append("")
    text = "\n".join(lines) + "\n"
    (OUT / "SUMMARY_E16RC.md").write_text(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
