"""E16-M2 tables: arm M (backprop on the learner's data pipeline) and oracle replay (the sign rule on the twin's joint
stream) on the two failing seeds, beside the failing learner and the twin.

Seed 400009 runs on the drifting stream (comparators from E16-F5); seed 600013 runs on block stages (comparators
from E16-F4). Writes exp45/SUMMARY_E16M2.md. Reads only; works on partial receipts (prints the checkpoints present).
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
F1 = ("add97", "sub97", "max97", "min97")
F3 = ("add73", "sub73", "max73", "min73")
HELD = ("+-", "-+", "><", "<>")
CASES = {  # seed: (stream, [(label, receipt tag)]), the failing learner first, the twin last
    400009: ("drift", [("T raw (E16-F5, failing)", "T_raw65536_drift_online"), ("M raw", "M_raw65536_drift_online"),
                       ("T oracle", "T_oracle_drift"), ("D twin (E16-F5)", "D_drift")]),
    600013: ("blocks", [("T raw (E16-F4, failing)", "T_raw65536"), ("M raw", "M_raw65536"),
                        ("T oracle", "T_oracle"), ("D twin (E16-F4)", "D")]),
}


def op(sc, n):
    return 100 * sc[n]["12"]["exact"] / sc[n]["12"]["n"]


def pair(sc, h):
    c = sc["compose"][h]
    return 100 * c["final"] / c["n"]


def fam(sc):
    return (sum(op(sc, n) for n in F1) / 4, sum(pair(sc, h) for h in HELD) / 4, sum(op(sc, n) for n in F3) / 4)


def load(seed, tag):
    p = OUT / f"e16_life_{tag}_{seed}.json"
    return json.load(open(p))["stages"] if p.exists() else None


def main():
    L = ["# SUMMARY_E16M2: rule or data on the two failing seeds", "",
         "Generated by `e16m2_tables.py` (reads only). Operations are exact answers (%) at k = 12 on the sealed panels; "
         "held pairs are final-answer accuracy (%). Checkpoint 0 is the birth. Seed 400009: drifting stream, online "
         "admission (comparators from E16-F5). Seed 600013: block stages (comparators from E16-F4).", ""]
    for seed, (stream, arms) in CASES.items():
        runs = [(lab, tag, load(seed, tag)) for lab, tag in arms]
        twin = runs[-1][2]
        L += [f"## Seed {seed} ({stream})", "", "### Family means and ratio to the twin after the last checkpoint", "",
              "| Arm | Checkpoints | mod-97 ops | Held comp | mod-73 ops | Ratios to twin | +- | -+ | >< | <> | panels |",
              "|---|---:|---:|---:|---:|---|---:|---:|---:|---:|---|"]
        for lab, tag, st in runs:
            if st is None:
                L.append(f"| {lab} | not present |||||||||"); continue
            sc = st[-1]["scores"]; v = fam(sc)
            r = "" if twin is None or len(twin) < 7 or len(st) < 7 else " · ".join(f"{a / b:.2f}" for a, b in zip(v, fam(twin[-1]["scores"])))
            panels = "re-keyed" if st[0].get("settings", {}).get("panels") else "old"
            L.append(f"| {lab} | {len(st) - 1} | {v[0]:.1f} | {v[1]:.1f} | {v[2]:.1f} | {r} | " +
                     " | ".join(f"{pair(sc, h):.1f}" for h in HELD) + f" | {panels} |")
        L += ["", "### Every checkpoint: mod-97 operations and held pairs", "",
              "| Arm | Ckpt | add97 | sub97 | max97 | min97 | mod-97 mean | +- | -+ | >< | <> | held mean |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for lab, tag, st in runs:
            for i, s in enumerate(st or []):
                sc = s["scores"]; v = fam(sc)
                L.append(f"| {lab} | {i} | " + " | ".join(f"{op(sc, n):.1f}" for n in F1) + f" | {v[0]:.1f} | " +
                         " | ".join(f"{pair(sc, h):.1f}" for h in HELD) + f" | {v[1]:.1f} |")
        L.append("")
    (OUT / "SUMMARY_E16M2.md").write_text("\n".join(L) + "\n")
    print("wrote", OUT / "SUMMARY_E16M2.md")


if __name__ == "__main__":
    main()
