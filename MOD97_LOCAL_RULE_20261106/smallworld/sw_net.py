"""E39 (brief OPUS_TASK_E39_SMALL_WORLD_PROTOCOL_L0_L1_20261115.md, revision 2): the small world's learner.

A GRU of E26's form, narrower. The class holds the parameter names of arch20.NetRNN("gru") (arch20.py lines 36-50), created in the same
order, with kind = "gru" and units = U, so that arch26.forward(m, x, local, True) runs on it unchanged:

    book = Embedding(258, 8, padding_idx=257)   (BOS, as arch20.py line 43)
    l1 = Linear(8, H); rnn = GRU(H, U); lm = Linear(U, H); l2 = Linear(H, H); l3 = Linear(H, 257)

Default H = U = 64 (52,625 parameters, the embedding table included). Initial values: T.manual_seed(world_seed), then the constructor.

    step(m, opt, items, local)   exp26_candidate.step's text (lines 84-91): exp45.batch_tensor, arch26.forward(m, x, local, True),
                                 answer-masked cross entropy, zero_grad, backward, one AdamW step. local=False: backprop; True: the sweep.
    make_opt(m, lr, wd)          AdamW, betas (0.9, 0.98), the embedding table in a group of its own without decay, as
                                 exp16_integrated.adamw16 (lines 176-187) with E16_BOOKDECAY=off. One optimizer for the whole life.
    answer(m, prompts)           greedy generation of at most 3 bytes under T.no_grad(), through arch26.forward (the same forward values
                                 as training). Returns the generated bytes; an item is right if all three are its answer.
"""
import sys
from pathlib import Path

import torch as T
from torch import nn
from torch.nn.functional import cross_entropy

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import arch26                         # noqa: E402  (imports arch20, exp11_cell, exp45, exp3_state, mod97_local; nothing edited)
import exp45 as X                     # noqa: E402

T.set_num_threads(1)
EOS, BOS = X.EOS, X.BOS
assert (EOS, BOS) == (256, 257)
H_DEFAULT = U_DEFAULT = 64
ANSWER_BYTES = 3


class SWNet(nn.Module):
    """arch20.NetRNN("gru")'s parameters under its names and in its order, at width H and U units."""

    def __init__(self, H=H_DEFAULT, U=U_DEFAULT):
        super().__init__()
        self.kind = "gru"
        self.width = H
        self.book = nn.Embedding(258, 8, padding_idx=BOS)
        self.l1 = nn.Linear(8, H)
        self.units = U
        self.rnn = nn.GRU(H, U, num_layers=1, batch_first=True)
        self.lm = nn.Linear(U, H)
        self.l2 = nn.Linear(H, H)
        self.l3 = nn.Linear(H, 257)


def new_net(world_seed, H=H_DEFAULT, U=U_DEFAULT):
    T.manual_seed(world_seed)
    return SWNet(H, U)


def n_params(m):
    return sum(p.numel() for p in m.parameters())


def make_opt(m, lr, wd):
    """As exp16_integrated.adamw16 with E16_BOOKDECAY=off and nothing frozen."""
    learn = list(m.named_parameters())
    groups = [{"params": [p for n, p in learn if not n.startswith("book.")]},
              {"params": [p for n, p in learn if n.startswith("book.")], "weight_decay": 0.0}]
    return T.optim.AdamW(groups, lr=lr, weight_decay=wd, betas=(.9, .98))


def opt_groups(m, opt):
    names = {id(p): n for n, p in m.named_parameters()}
    return [dict(weight_decay=g["weight_decay"], lr=g["lr"], betas=list(g["betas"]), params=[names[id(p)] for p in g["params"]])
            for g in opt.param_groups]


def step(m, opt, items, local):
    """exp26_candidate.step, line for line. items: list of (prompt, target)."""
    x, y, mask = X.batch_tensor(items)
    logits = arch26.forward(m, x, local, True)[0]
    loss = cross_entropy(logits[mask], y[mask])
    opt.zero_grad()
    loss.backward()
    opt.step()
    return float(loss.detach())


@T.no_grad()
def answer(m, prompts):
    """Greedy generation of ANSWER_BYTES bytes for each prompt (a list of byte lists). Every row is read at its own last position, so
    the right padding of exp45.batch_tensor's layout (BOS after the row) never enters a row's state. Returns a list of byte lists."""
    rows = [list(p) for p in prompts]
    out = [[] for _ in rows]
    for _ in range(ANSWER_BYTES):
        L = max(len(r) for r in rows) + 1
        x = T.full((len(rows), L), BOS, dtype=T.long)
        for i, r in enumerate(rows):
            x[i, 1:len(r) + 1] = T.tensor(r)
        logits = arch26.forward(m, x, False, True)[0]
        last = T.tensor([len(r) for r in rows])                      # position of the row's last byte in x (BOS at 0)
        nxt = logits[T.arange(len(rows)), last].argmax(-1).tolist()
        for i, b in enumerate(nxt):
            out[i].append(b); rows[i].append(b)
    return out
