"""E28 stage 2 summary: from the twelve E28 receipts (exp45/e28) and E26's answer-target receipts only. No readings are applied.

    python3 e28_summarize.py        writes exp45/e28/E28_BIRTHS.json and exp45/e28/E28_BIRTHS.md

Hard mean: (add89 + sub89 exact at k = 12, whole answers, sealed panels of 300) / 600 x 100, as the brief's E26 figures (98.0/98.2/99.8, 98.5/98.7/93.7).
Prediction outcomes are computed as worded in E28_PREDICTIONS.md; nothing else is concluded.
"""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
D = HERE / "exp45" / "e28"
E26 = HERE / "exp45" / "e26"
SEEDS = (73129, 93683, 116089)
NEW = ("S-all", "B-all", "S-bal", "B-bal")
ROLES = ("distractor", "operand", "structural", "answer")


def hard(row):
    s = row["sealed"]
    return (s["add89"]["12"]["exact"] + s["sub89"]["12"]["exact"]) / 6


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main():
    out = dict(births={}, e26_answer={}, problems=[])
    for a in ("S", "B"):
        for s in SEEDS:
            r = json.loads((E26 / f"e26_dev_{a}_{s}.json").read_text())
            out["e26_answer"][f"{a}-ans {s}"] = dict(final=hard(r["curve"][-1]), curve=[(x["step"], hard(x)) for x in r["curve"]])
    for arm in NEW:
        for s in SEEDS:
            f = D / f"e28_dev_{arm}_{s}.json"
            if not f.exists():
                out["problems"].append(f"{f.name}: missing"); continue
            r = json.loads(f.read_text())
            if r.get("complete") is not True:
                out["problems"].append(f"{f.name}: not complete (last row {r['curve'][-1]['step'] if r['curve'] else None})")
            curve = [(x["step"], hard(x)) for x in r["curve"]]
            peak = max(curve, key=lambda t: t[1]) if curve else None
            files_ok = {}
            for st, w in r.get("row_weights", {}).items():
                p = D / w["file"]
                files_ok[st] = p.exists() and sha(p) == w["sha256"]
            blocks = r["role_curve"]
            out["births"][f"{arm} {s}"] = dict(
                arm=arm, seed=s, targets=r["targets"], complete=r.get("complete"), final=curve[-1][1] if curve else None,
                peak=dict(row=peak[0], hard=peak[1]) if peak else None, curve=curve,
                curve_by_task_k12={x["step"]: {n: x["sealed"][n]["12"]["exact"] for n in x["sealed"]} for x in r["curve"]},
                finite=r["finite"], data_digest_checks=[x["data_digest_check"] for x in r["curve"]],
                role_blocks=len(blocks),
                role_curve=[dict(block_end=b["block_end"], train_loss=b["train_loss"], **{k: b["by_role"][k]["mean"] for k in ROLES}) for b in blocks],
                row_weight_files_match_hash=files_ok, weights_sha256=r.get("weights_sha256"), tensors_sha256=r.get("tensors_sha256"),
                cpu_total=r.get("cpu_total"), cpu_per_update=r.get("cpu_per_update"), host=r["provenance"]["host"],
                git=r["provenance"]["git"], sources_sha256=r["provenance"]["sources_sha256"])
    B = out["births"]; A = out["e26_answer"]
    have = lambda arm: all(f"{arm} {s}" in B and B[f"{arm} {s}"]["complete"] for s in SEEDS)
    fin = lambda arm, s: B[f"{arm} {s}"]["final"]
    P = {}
    if have("B-all"):
        v = [fin("B-all", s) for s in SEEDS]
        P["P28.1"] = dict(statement="B-all ends at a hard mean of at least 85 in all three seeds", values=v, held=all(x >= 85 for x in v))
    if have("S-all"):
        v = [fin("S-all", s) for s in SEEDS]
        P["P28.2"] = dict(statement="S-all ends at or below 10 in all three seeds", values=v, held=all(x <= 10 for x in v))
    if have("S-all") and have("S-bal"):
        d = [fin("S-bal", s) - fin("S-all", s) for s in SEEDS]
        P["P28.3"] = dict(statement="S-bal ends at least 20 points above S-all in at least two of three seeds", S_bal_minus_S_all=d,
                          seeds_meeting=sum(x >= 20 for x in d), held=sum(x >= 20 for x in d) >= 2)
    if have("B-bal"):
        d = [fin("B-bal", s) - A[f"B-ans {s}"]["final"] for s in SEEDS]
        P["P28.4"] = dict(statement="B-bal ends within 10 points of B-ans in all three seeds", B_bal_minus_B_ans=d, held=all(abs(x) <= 10 for x in d))
    out["predictions"] = P
    out["across_seeds_descriptive"] = {arm: dict(final_mean=sum(fin(arm, s) for s in SEEDS) / 3, final_max=max(fin(arm, s) for s in SEEDS),
                                                 final_min=min(fin(arm, s) for s in SEEDS)) for arm in NEW if have(arm)}
    (D / "E28_BIRTHS.json").write_text(json.dumps(out, indent=1))
    md = ["# E28 births: numbers from the receipts (no readings applied)", "",
          "Hard mean = (add89 + sub89 exact at k = 12, whole answers, 300 each) / 600 x 100. Generated by `e28_summarize.py`.", ""]
    if out["problems"]:
        md += ["**Problems:** " + "; ".join(out["problems"]), ""]
    md += ["## Final and peak hard means", "", "| Arm | " + " | ".join(f"{s} final | {s} peak (row)" for s in SEEDS) + " |",
           "|---|" + "---|---|" * 3]
    for arm in NEW + ("S-ans", "B-ans"):
        cells = []
        for s in SEEDS:
            if arm.endswith("-ans"):
                c = A[f"{arm} {s}"]["curve"]; pk = max(c, key=lambda t: t[1])
                cells += [f"{A[f'{arm} {s}']['final']:.1f}", f"{pk[1]:.1f} ({pk[0]})"]
            elif f"{arm} {s}" in B:
                b = B[f"{arm} {s}"]; cells += [f"{b['final']:.1f}", f"{b['peak']['hard']:.1f} ({b['peak']['row']})"]
            else:
                cells += ["–", "–"]
        md.append(f"| {arm}{' (E26)' if arm.endswith('-ans') else ''} | " + " | ".join(cells) + " |")
    md += ["", "## Six-row curves (hard mean at rows 4096 … 24576)", ""]
    for k, b in B.items():
        md.append(f"- {k}: " + ", ".join(f"{h:.1f}" for _, h in b["curve"]))
    md += ["", "## Loss by role (mean CE per target position, blocks of 512 updates; every 8th block shown, all 48 in E28_BIRTHS.json)", ""]
    for k, b in B.items():
        md += [f"**{k}**", "", "| block end | train loss | distractor | operand | structural | answer |", "|---|---|---|---|---|---|"]
        for rc in b["role_curve"]:
            if rc["block_end"] % 4096 == 512 or rc["block_end"] == b["role_curve"][-1]["block_end"]:
                md.append(f"| {rc['block_end']} | {rc['train_loss']:.3f} | " + " | ".join(f"{rc[r]:.3f}" for r in ROLES) + " |")
        md.append("")
    md += ["## Predictions, as computed", ""]
    for n, p in P.items():
        md.append(f"- **{n}** ({p['statement']}): {'held' if p['held'] else 'not held'}; " +
                  "; ".join(f"{k} = {[round(x, 1) for x in v] if isinstance(v, list) else v}" for k, v in p.items() if k not in ("statement", "held")))
    md += ["", "## Across seeds (descriptive; nothing predicted of max/min)", ""]
    for arm, v in out["across_seeds_descriptive"].items():
        md.append(f"- {arm}: mean {v['final_mean']:.1f}, max {v['final_max']:.1f}, min {v['final_min']:.1f}")
    (D / "E28_BIRTHS.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
