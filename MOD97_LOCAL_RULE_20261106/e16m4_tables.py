"""E16-M4 tables (read-only). Half a: share 0.75 against share 0.5 on the six E16-F7 seeds. Half b: the share curve of E16-M3 extended to
0.875 and 0.9375 on 400009, 600013, 300007. Writes exp45/E16M4_TABLES.md. Works on partial receipts (last checkpoint present)."""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
F1 = ("add97", "sub97", "max97", "min97"); F3 = ("add73", "sub73", "max73", "min73"); HELD = ("+-", "-+", "><", "<>")
A_SEEDS = (1100009, 1200007, 1300021, 1400017, 1500007, 1600033)
B_SEEDS = (400009, 600013, 300007)
TAG = {0.0: "_rs0", 0.25: "_rs25", 0.5: "", 0.75: "_rs75", 0.875: "_rs88", 0.9375: "_rs94"}


def load(name):
    p = OUT / name
    return json.loads(p.read_text())["stages"] if p.exists() else None


def ops(sc, f): return 100 * sum(sc[n]["12"]["exact"] / sc[n]["12"]["n"] for n in f) / 4
def pr(sc, h): return 100 * sc["compose"][h]["final"] / sc["compose"][h]["n"]
def comp(sc): return sum(pr(sc, h) for h in HELD) / 4
def hard(sc): return (pr(sc, "+-") + pr(sc, "-+")) / 2


def life(seed, share): return load(f"e16_life_T_raw65536_drift_online{TAG[share]}_{seed}.json")


def summ(st, tw):
    sc = st[-1]["scores"]
    r = dict(ck=len(st) - 1, f1=ops(sc, F1), comp=comp(sc), f3=ops(sc, F3), hard=hard(sc), pm=pr(sc, "+-"), mp=pr(sc, "-+"))
    r.update(r1=r["f1"] / ops(tw, F1), rc=r["comp"] / comp(tw), r3=r["f3"] / ops(tw, F3), rh=r["hard"] / hard(tw))
    r["family_gate"] = min(r["r1"], r["rc"], r["r3"]) >= .8; r["hard_gate"] = r["rh"] >= .8
    if len(st) == 7:
        r["pm46"] = pr(st[6]["scores"], "+-") - pr(st[4]["scores"], "+-"); r["mp46"] = pr(st[6]["scores"], "-+") - pr(st[4]["scores"], "-+")
        r["peak34"] = max(hard(st[3]["scores"]), hard(st[4]["scores"]))
    return r


def main():
    L = ["# E16-M4 tables", "", "Generated by `e16m4_tables.py` (read-only). Last checkpoint unless stated (the `ck` column shows how many are present). "
         "Operations: exact at k = 12, family mean; compositions: final answer; hard pairs = mean of `+-` and `-+`; ratios to the drift twin; "
         "family gate = all three family ratios ≥ 0.80; hard-pair gate = hard-pair ratio ≥ 0.80.", "",
         "## Half a: share 0.5 (E16-F7) against share 0.75", "",
         "| seed | share | ck | mod-97 | comp | mod-73 | ratio 97 | ratio comp | ratio 73 | hard | hard ratio | family gate | hard gate | +- ck4→6 | -+ ck4→6 |",
         "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---:|---:|"]
    res = {}
    for s in A_SEEDS:
        tw = load(f"e16_life_D_drift_{s}.json")[6]["scores"]
        for sh in (0.5, 0.75):
            st = life(s, sh)
            if not st:
                L.append(f"| {s} | {sh} | not present | | | | | | | | | | | | |"); continue
            r = summ(st, tw); res[(s, sh)] = r
            L.append(f"| {s} | {sh} | {r['ck']} | {r['f1']:.1f} | {r['comp']:.1f} | {r['f3']:.1f} | {r['r1']:.3f} | {r['rc']:.3f} | {r['r3']:.3f} | {r['hard']:.1f} | "
                     f"{r['rh']:.3f} | {'yes' if r['family_gate'] else 'no'} | {'yes' if r['hard_gate'] else 'no'} | "
                     f"{r.get('pm46', float('nan')):+.1f} | {r.get('mp46', float('nan')):+.1f} |")
    L += ["", "## Half b: the share curve on the E16-M3 seeds", ""]
    for s in B_SEEDS:
        tw = load(f"e16_life_D_drift_{s}.json")[6]["scores"]
        L += [f"### Seed {s}", "", "| share | ck | mod-97 | hard | comp ratio | mod-73 | hard peak ck 3–4 | family gate | min family ratio |",
              "|---:|---:|---:|---:|---:|---:|---:|---|---:|"]
        for sh in (0.0, 0.25, 0.5, 0.75, 0.875, 0.9375):
            st = life(s, sh)
            if not st:
                L.append(f"| {sh} | not present | | | | | | | |"); continue
            r = summ(st, tw); res[(s, sh)] = r
            L.append(f"| {sh} | {r['ck']} | {r['f1']:.1f} | {r['hard']:.1f} | {r['rc']:.3f} | {r['f3']:.1f} | {r.get('peak34', float('nan')):.1f} | "
                     f"{'yes' if r['family_gate'] else 'no'} | {min(r['r1'], r['rc'], r['r3']):.3f} |")
        L.append("")
    L += ["## Trajectories (every checkpoint): mod-97 mean · hard pairs · mod-73 mean", "", "| seed | share | mod-97 | hard | mod-73 |", "|---|---:|---|---|---|"]
    for s in A_SEEDS + B_SEEDS:
        for sh in ((0.5, 0.75) if s in A_SEEDS else (0.75, 0.875, 0.9375)):
            st = life(s, sh)
            if st:
                L.append(f"| {s} | {sh} | " + " ".join(f"{ops(x['scores'], F1):.0f}" for x in st) + " | "
                         + " ".join(f"{hard(x['scores']):.0f}" for x in st) + " | " + " ".join(f"{ops(x['scores'], F3):.0f}" for x in st) + " |")
    (OUT / "E16M4_TABLES.md").write_text("\n".join(L) + "\n")
    json.dump({f"{k[0]}_{k[1]}": v for k, v in res.items()}, open(OUT / "E16M4_TABLES.json", "w"), indent=1)
    print("\n".join(L[:40]))


if __name__ == "__main__":
    main()
