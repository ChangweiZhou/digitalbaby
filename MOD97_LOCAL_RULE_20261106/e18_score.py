"""E18: tables and verdicts for the twelve births (reads only; writes exp45/E18_TABLES.md).

Arms (brief OPUS_TASK_E18_LOCAL_HEADS_BIRTHS_20261110.md): B0 `_bT_tall`, B1 `_lh`, B2 `_lh_bT_tall`, B3 `_lh_bT`, files
exp45/e17_dev_bank2_nbd<tag>_<seed>.json. References on file: two banks by end-to-end backprop (e17_dev_bank2_nbd_<seed>) and one
bank by backprop (e17_dev_bank_<seed>). Hard mean = mean of add89 and sub89 at k = 12, final checkpoint, main head unless the first
bank's head is named; max/min mean likewise for max89 and min89.
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
SEEDS = (73129, 93683, 116089)
ARMS = {"B0": "_bT_tall", "B1": "_lh", "B2": "_lh_bT_tall", "B3": "_lh_bT"}
DESC = {"B0": "relay between banks, weight signs, credit through time", "B1": "no relay; exact backprop inside each bank",
        "B2": "no relay; weight signs, credit through time inside each bank", "B3": "no relay; weight signs, trace on write synapses only"}
OPS = ("add89", "sub89", "max89", "min89")
KS = ("0", "4", "8", "12", "20")


def pct(v):
    return 100 * v["exact"] / v["n"]


def load(stem, seed):
    p = OUT / f"e17_dev_{stem}_{seed}.json"
    return json.load(open(p)) if p.exists() else None


def final(j, key="sealed"):
    r = j["curve"][-1]
    return {n: pct(r[key][n]["12"]) for n in OPS} if key in ("sealed", "head1") else {n: pct(r[key][n]) for n in OPS}


def hard(d):
    return (d["add89"] + d["sub89"]) / 2


def mm(d):
    return (d["max89"] + d["min89"]) / 2


def main():
    L = ["# E18_TABLES: births with a next-byte target at every bank", "",
         "Generated by `e18_score.py` (reads only). Exact answers (%) on the sealed development panels (300 items per operation and "
         "number of distractors k). Hard mean = mean of add89 and sub89 at k = 12 at the final checkpoint (24,576 updates); max/min mean "
         "likewise. Main head unless `head1` (the first bank's own head) is named.", ""]
    ref2 = {s: load("bank2_nbd", s) for s in SEEDS}
    ref1 = {s: load("bank", s) for s in SEEDS}
    res = {}
    for a, tag in ARMS.items():
        for s in SEEDS:
            j = load(f"bank2_nbd{tag}", s)
            if j:
                res[a, s] = j
    # summary table
    L += ["## Final checkpoint, k = 12", "",
          "| Arm | Seed | add89 | sub89 | max89 | min89 | Hard mean | Max/min mean | Ref. two banks (hard) | Ref. one bank (hard) | Ratio to two-bank ref. | CPU-s |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    H = {}
    for a in ARMS:
        for s in SEEDS:
            if (a, s) not in res:
                L.append(f"| {a} | {s} | not finished |||||||||| "); continue
            f = final(res[a, s]); r2, r1 = hard(final(ref2[s])), hard(final(ref1[s]))
            H[a, s] = (hard(f), mm(f), f)
            L.append(f"| {a} | {s} | " + " | ".join(f"{f[n]:.1f}" for n in OPS) + f" | **{hard(f):.1f}** | {mm(f):.1f} | {r2:.1f} | {r1:.1f} | "
                     f"{hard(f) / r2:.2f} | {res[a, s]['curve'][-1]['cpu']:.0f} |")
    L += ["", "References at k = 12 (final): two banks by end-to-end backprop, one bank by backprop (made on the owner's machine).", "",
          "| Reference | Seed | add89 | sub89 | max89 | min89 | Hard mean | Max/min mean |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for lab, R in (("two banks, backprop", ref2), ("one bank, backprop", ref1)):
        for s in SEEDS:
            f = final(R[s]); L.append(f"| {lab} | {s} | " + " | ".join(f"{f[n]:.1f}" for n in OPS) + f" | {hard(f):.1f} | {mm(f):.1f} |")
    # head1 and silenced
    L += ["", "## The first bank's own head (local-heads arms) and the silenced score, final checkpoint, k = 12", "",
          "| Arm | Seed | head1 add89 | head1 sub89 | head1 max89 | head1 min89 | head1 hard mean | Silenced add89 / sub89 / max89 / min89 (main head) |",
          "|---|---:|---:|---:|---:|---:|---:|---|"]
    for (a, s), j in res.items():
        r = j["curve"][-1]; si = final(j, "silenced_k12")
        if "head1" in r:
            h = final(j, "head1")
            L.append(f"| {a} | {s} | " + " | ".join(f"{h[n]:.1f}" for n in OPS) + f" | {hard(h):.1f} | " + " / ".join(f"{si[n]:.1f}" for n in OPS) + " |")
        else:
            L.append(f"| {a} | {s} | – | – | – | – | – | " + " / ".join(f"{si[n]:.1f}" for n in OPS) + " |")
    # curves
    L += ["", "## Birth curves: each operation at k = 0 / 4 / 8 / 12 / 20, every 4,096 updates", ""]
    for (a, s), j in res.items():
        L += [f"### {a} ({DESC[a]}), seed {s}", "", "| Updates | loss | " + " | ".join(OPS) + " | CPU-s |", "|---:|---:|---|---|---|---|---:|"]
        for r in j["curve"]:
            L.append(f"| {r['step']} | {r['loss']:.3f} | " + " | ".join(" / ".join(f"{pct(r['sealed'][n][k]):.0f}" for k in KS) for n in OPS)
                     + f" | {r['cpu']:.0f} |")
        if "head1" in j["curve"][-1]:
            h = j["curve"][-1]["head1"]
            L.append(f"| head1 at {j['curve'][-1]['step']} | | " + " | ".join(" / ".join(f"{pct(h[n][k]):.0f}" for k in KS) for n in OPS) + " | |")
        L.append("")
    # verdicts
    if len(res) == 12:
        L += ["## Verdicts", ""]
        h1 = {s: final(res["B1", s], "head1")["add89"] for s in SEEDS}
        p1 = all(x < 45 for x in h1.values())
        L.append(f"- **P18.1** B1 head1 add89 < 45 in all three: {', '.join(f'{s} {h1[s]:.1f}' for s in SEEDS)} → **{'holds' if p1 else 'misses'}**.")
        r2 = {s: hard(final(ref2[s])) for s in SEEDS}
        n70 = sum(H["B1", s][0] >= 70 for s in SEEDS); below = all(H["B1", s][0] < r2[s] for s in SEEDS)
        L.append(f"- **P18.2** B1 hard mean ≥ 70 in ≥ 2 and below the reference in all three: "
                 + ", ".join(f"{s} {H['B1', s][0]:.1f} (ref {r2[s]:.1f})" for s in SEEDS) + f"; ≥ 70 in {n70}, below ref in all: {below} → **{'holds' if n70 >= 2 and below else 'misses'}**.")
        n = sum(H["B0", s][0] >= .8 * r2[s] for s in SEEDS)
        L.append(f"- **P18.3** B0 hard mean ≥ 0.80 of the reference in ≥ 2: " + ", ".join(f"{s} {H['B0', s][0] / r2[s]:.2f}" for s in SEEDS)
                 + f"; {n} of 3 → **{'holds' if n >= 2 else 'misses'}**.")
        n = sum(H["B0", s][0] - H["B1", s][0] >= 5 for s in SEEDS)
        L.append(f"- **P18.4** B0 − B1 hard mean ≥ 5 in ≥ 2: " + ", ".join(f"{s} {H['B0', s][0] - H['B1', s][0]:+.1f}" for s in SEEDS)
                 + f"; {n} of 3 → **{'holds' if n >= 2 else 'misses'}**.")
        n = sum(abs(H["B2", s][0] - H["B1", s][0]) <= 10 for s in SEEDS)
        L.append(f"- **P18.5** |B2 − B1| hard mean ≤ 10 in ≥ 2: " + ", ".join(f"{s} {H['B2', s][0] - H['B1', s][0]:+.1f}" for s in SEEDS)
                 + f"; {n} of 3 → **{'holds' if n >= 2 else 'misses'}**.")
        a = all(H["B3", s][0] < 40 for s in SEEDS); b = all(H["B2", s][1] - H["B3", s][1] >= 20 for s in SEEDS)
        L.append(f"- **P18.6** B3 hard mean < 40 in all three (" + ", ".join(f"{s} {H['B3', s][0]:.1f}" for s in SEEDS)
                 + f": {a}) and B3 max/min mean ≥ 20 below B2's in all three (" + ", ".join(f"{s} {H['B2', s][1] - H['B3', s][1]:+.1f}" for s in SEEDS)
                 + f" B2 − B3: {b}) → **{'holds' if a and b else 'misses'}**.")
    else:
        L += [f"Not yet finished: {', '.join(f'{a} {s}' for a in ARMS for s in SEEDS if (a, s) not in res)}."]
    (OUT / "E18_TABLES.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
