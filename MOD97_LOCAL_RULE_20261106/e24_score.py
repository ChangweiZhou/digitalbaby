"""E24: tables and verdicts from the receipts (reads only; writes exp45/e24/E24_TABLES.md).

Brief OPUS_TASK_E24_EVERY_BYTE_CAUSE_20261111.md, revision 4. Endpoint: the final checkpoint, k = 12, the top head, whole answers.
Hard mean = mean of add89 and sub89; max/min mean = mean of max89 and min89 (read against 50, the operand-copy level).
Baselines: D-ans on this host class (93.2 / 92.8 / 92.8), T-ans the cloud-born originals (87.5 / 90.7 / 84.7).
"""
import json
from pathlib import Path

E = Path(__file__).resolve().parent / "exp45" / "e24"
SEEDS = (73129, 93683, 116089)
ARMS = {"D-ans": "baselines/D_ans_e17_dev_bank2_nbd_{}.json", "T-ans": "baselines/T_ans_e17_dev_bank2_nbd_bT_tall_{}.json",
        "D-all": "e17_dev_bank2_nbd_lossall_{}.json", "T-all": "e17_dev_bank2_nbd_bT_tall_lossall_{}.json",
        "T-bal": "e17_dev_bank2_nbd_bT_tall_lossall_bal_{}.json"}
OPS = ("add89", "sub89", "max89", "min89")
KS = ("0", "4", "8", "12", "20")


def load(a, s):
    p = E / ARMS[a].format(s)
    return json.load(open(p)) if p.exists() else None


def pct(sd, op, k="12", key="exact"):
    return 100 * sd[op][k][key] / sd[op][k]["n"]


def hard(sd):
    return (pct(sd, "add89") + pct(sd, "sub89")) / 2


def mm(sd):
    return (pct(sd, "max89") + pct(sd, "min89")) / 2


def main():
    R = {(a, s): load(a, s) for a in ARMS for s in SEEDS}
    H = {k: hard(v["curve"][-1]["sealed"]) for k, v in R.items() if v}
    L = ["# E24_TABLES: every-byte targets at birth", "",
         "Generated by `e24_score.py` (reads only). Sealed panels, top head, whole own answers with the end symbol (`exact`); "
         "hard mean = add89 and sub89 at k = 12; max/min mean read against 50.", "",
         "## End of birth (24,576 updates), k = 12", "",
         "| Arm | Seed | add89 | sub89 | max89 | min89 | Hard mean | Max/min mean | Final loss | CPU-s | Weights sha256 (16) |",
         "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for a in ARMS:
        for s in SEEDS:
            j = R[a, s]
            if not j:
                L.append(f"| {a} | {s} | not run | | | | | | | | |")
                continue
            c = j["curve"][-1]; sd = c["sealed"]
            L.append(f"| {a} | {s} | " + " | ".join(f"{sd[o]['12']['exact']}" for o in OPS)
                     + f" | {hard(sd):.1f} | {mm(sd):.1f} | {c['loss']:.4f} | {c.get('cpu', 0):.0f} | {str(j['weights_sha256'])[:16] if j.get('weights_sha256') else 'not in receipt; manifest pins it'} |")
    L += ["", "Counts are of 300 per panel.", "", "## Hard-mean curve (k = 12) at each checkpoint", "",
          "| Arm | Seed | 4,096 | 8,192 | 12,288 | 16,384 | 20,480 | 24,576 |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for a in ARMS:
        for s in SEEDS:
            if R[a, s]:
                L.append(f"| {a} | {s} | " + " | ".join(f"{hard(c['sealed']):.1f}" for c in R[a, s]["curve"]) + " |")
    L += ["", "## Penalties of every-byte targets and their difference (hard mean, points)", "",
          "| Seed | D-ans − D-all | T-ans − T-all | Interaction (T penalty − D penalty) | T-bal − T-all |",
          "|---:|---:|---:|---:|---:|"]
    for s in SEEDS:
        def g(a):
            return H.get((a, s))
        dp = g("D-ans") - g("D-all") if g("D-ans") is not None and g("D-all") is not None else None
        tp = g("T-ans") - g("T-all") if g("T-ans") is not None and g("T-all") is not None else None
        tb = g("T-bal") - g("T-all") if g("T-bal") is not None and g("T-all") is not None else None
        f = lambda x: "—" if x is None else f"{x:+.1f}"
        L.append(f"| {s} | {f(dp)} | {f(tp)} | {f(tp - dp if dp is not None and tp is not None else None)} | {f(tb)} |")
    L += ["", "## Sealed scores at every checkpoint (exact of 300, k = 0 / 4 / 8 / 12 / 20)", ""]
    for a in ARMS:
        for s in SEEDS:
            j = R[a, s]
            if not j:
                continue
            L += [f"### {a}, seed {s}", "", "| Step | loss | " + " | ".join(OPS) + " | cpu |", "|---:|---:|---|---|---|---|---:|"]
            for c in j["curve"]:
                L.append(f"| {c['step']} | {c['loss']:.4f} | " + " | ".join("/".join(str(c['sealed'][o][k]['exact']) for k in KS) for o in OPS)
                         + f" | {c.get('cpu', 0):.0f} |")
            L.append("")
    L += ["## Embedding movement by symbol role (`book_shift_by_role`, final checkpoint)", "",
          "Recorded by the harness for the new births; the baselines' receipts carry it where their harness wrote it.", "",
          "| Arm | Seed | operator | digit | equals | distractor letter | task code | separator |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for a in ARMS:
        for s in SEEDS:
            j = R[a, s]
            b = j["curve"][-1].get("book_shift_by_role") if j else None
            if b:
                L.append(f"| {a} | {s} | " + " | ".join(f"{b.get(r, float('nan')):.4f}" for r in ("operator", "digit", "equals", "distractor letter", "task code", "separator")) + " |")
            elif j:
                L.append(f"| {a} | {s} | (not recorded in this receipt) | | | | | |")
    L += ["", "## Credit census at the first update (`credit_census_first_update.by_role`: with gradient / present)", "",
          "| Arm | Seed | operator | digit | equals | distractor letter | task code | BOS/EOS |", "|---|---:|---|---|---|---|---|---|"]
    for a in ARMS:
        for s in SEEDS:
            j = R[a, s]
            cc = (j or {}).get("credit_census_first_update", {}).get("by_role")
            if cc:
                L.append(f"| {a} | {s} | " + " | ".join(f"{cc[r]['with_gradient']}/{cc[r]['present']}" for r in ("operator", "digit", "equals", "distractor letter", "task code", "BOS/EOS")) + " |")
    L += ["", "## Verdicts", ""]
    if all(("D-all", s) in H for s in SEEDS):
        n = sum(H["D-all", s] >= 60 for s in SEEDS)
        L.append(f"- **P24.1** D-all hard mean ≥ 60 in ≥ 2 seeds: " + ", ".join(f"{s} {H['D-all', s]:.1f}" for s in SEEDS) + f" → {n} of 3 → **{'holds' if n >= 2 else 'misses'}**.")
    if all(("T-all", s) in H for s in SEEDS):
        n = sum(H["T-all", s] <= 10 for s in SEEDS)
        L.append(f"- **P24.2** T-all hard mean ≤ 10 in all three: " + ", ".join(f"{s} {H['T-all', s]:.1f}" for s in SEEDS) + f" → {n} of 3 → **{'holds' if n == 3 else 'misses'}**.")
    if all(("T-bal", s) in H for s in SEEDS):
        n = sum(H["T-bal", s] >= 40 for s in SEEDS)
        L.append(f"- **P24.3** T-bal hard mean ≥ 40 in ≥ 2 seeds: " + ", ".join(f"{s} {H['T-bal', s]:.1f}" for s in SEEDS) + f" → {n} of 3 → **{'holds' if n >= 2 else 'misses'}**.")
    else:
        L.append("- P24.3: T-bal not finished on all three seeds.")
    (E / "E24_TABLES.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
