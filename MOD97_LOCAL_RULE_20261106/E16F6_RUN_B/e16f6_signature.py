"""E16-F6 tables beyond the summarizer: per-checkpoint learner/twin trajectories for the six E16-F6 seeds, and the twelve-seed
early-signature list (P16F6.5) with the Spearman correlation. Read-only; writes exp45/E16F6_SIGNATURE.md.

Twelve drift seeds: 73129, 93683, 116089 (E16-S), 200003, 300007, 400009 (E16-F5), 500011, 600013, 700027, 800011, 900007, 1000003 (E16-F6).
Learner: e16_life_T_raw65536_drift_online_<seed>.json; twin: e16_life_D_drift_<seed>.json.
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
F1 = ("add97", "sub97", "max97", "min97")
F3 = ("add73", "sub73", "max73", "min73")
HELD = ("+-", "-+", "><", "<>")
OLD = (73129, 93683, 116089, 200003, 300007, 400009)
NEW = (500011, 600013, 700027, 800011, 900007, 1000003)
SRC = {**{s: "E16-S" for s in OLD[:3]}, **{s: "E16-F5" for s in OLD[3:]}, **{s: "E16-F6" for s in NEW}}


def load(arm, s):
    p = OUT / (f"e16_life_T_raw65536_drift_online_{s}.json" if arm == "T" else f"e16_life_D_drift_{s}.json")
    return json.loads(p.read_text())["stages"] if p.exists() else None


def ops(sc, fam, k="12"):
    return 100 * sum(sc[n][k]["exact"] / sc[n][k]["n"] for n in fam) / len(fam)


def pair(sc, h):
    c = sc["compose"][h]
    return 100 * c["final"] / c["n"]


def comp(sc):
    return sum(pair(sc, h) for h in HELD) / 4


def ranks(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    r = [0.0] * len(xs)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for q in range(i, j + 1):
            r[order[q]] = (i + j) / 2 + 1
        i = j + 1
    return r


def spearman(x, y):
    rx, ry = ranks(x), ranks(y)
    mx, my = sum(rx) / len(rx), sum(ry) / len(ry)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    den = (sum((a - mx) ** 2 for a in rx) * sum((b - my) ** 2 for b in ry)) ** .5
    return num / den


def main():
    L = ["# E16-F6: trajectories and the twelve-seed early signature", "",
         "Generated by `e16f6_signature.py` (read-only). Operations: exact at k = 12; compositions: final answer, percent. "
         "Learner T = raw reservoir 65,536, online admission, drifting stream; twin D = backprop on the same drifting stream.", ""]
    for s in NEW:
        T, D = load("T", s), load("D", s)
        L += [f"## Seed {s}", ""]
        if not T or not D:
            L += ["receipts incomplete or missing", ""]; continue
        L += ["| Ck | arm | add97 | sub97 | max97 | min97 | mod-97 mean | +- | -+ | >< | <> | comp mean | mod-73 mean |", "|---|---|" + "---:|" * 11]
        for i in range(max(len(T), len(D))):
            for name, R in (("T", T), ("D", D)):
                if i >= len(R):
                    continue
                sc = R[i]["scores"]
                L.append(f"| {i} | {name} | " + " | ".join(f"{100 * sc[n]['12']['exact'] / sc[n]['12']['n']:.1f}" for n in F1) + f" | {ops(sc, F1):.1f} | "
                         + " | ".join(f"{pair(sc, h):.1f}" for h in HELD) + f" | {comp(sc):.1f} | {ops(sc, F3):.1f} |")
        L.append("")
    rows = []
    for s in OLD + NEW:
        T, D = load("T", s), load("D", s)
        if not T or not D or len(T) < 7 or len(D) < 7:
            continue
        t6, d6 = T[6]["scores"], D[6]["scores"]
        rows.append(dict(seed=s, src=SRC[s], ck2=ops(T[2]["scores"], F1), pm=pair(t6, "+-"), mp=pair(t6, "-+"),
                         r1=ops(t6, F1) / ops(d6, F1), rc=comp(t6) / comp(d6), r3=ops(t6, F3) / ops(d6, F3),
                         panels="old" if "panels" not in T[0]["settings"] else "new"))
    rows.sort(key=lambda r: r["ck2"])
    L += ["## Twelve-seed early signature (P16F6.5), sorted by the learner's checkpoint-2 mod-97 mean", "",
          "| Seed | source | panels | ck-2 mod-97 | final +- | final -+ | ratio mod-97 | ratio comp | ratio mod-73 | all three ≥ 0.80 |",
          "|---|---|---|---:|---:|---:|---:|---:|---:|---|"]
    for r in rows:
        L.append(f"| {r['seed']} | {r['src']} | {r['panels']} | {r['ck2']:.1f} | {r['pm']:.1f} | {r['mp']:.1f} | {r['r1']:.3f} | {r['rc']:.3f} | {r['r3']:.3f} | "
                 f"{'yes' if min(r['r1'], r['rc'], r['r3']) >= .8 else 'no'} |")
    if len(rows) >= 3:
        rho = spearman([r["ck2"] for r in rows], [r["pm"] for r in rows])
        low = [r for r in rows if r["ck2"] < 70]
        high = [r for r in rows if r["ck2"] > 80]
        L += ["", f"Seeds: {len(rows)}. Spearman rho (ck-2 mod-97 mean vs final +-): **{rho:.3f}** (limit ≥ 0.5).",
              f"Below 70 at ck 2: {', '.join(f'{r['seed']} (+- {r['pm']:.1f})' for r in low) or 'none'}; all end below 60: {all(r['pm'] < 60 for r in low)}.",
              f"Above 80 at ck 2: {len(high)} seeds; all end above 65: {all(r['pm'] > 65 for r in high)}"
              + (f" (exceptions: {', '.join(f'{r['seed']} {r['pm']:.1f}' for r in high if r['pm'] <= 65)})" if not all(r['pm'] > 65 for r in high) else "") + "."]
        newrows = [r for r in rows if r["panels"] == "new"]
        if len(newrows) >= 3:
            L.append(f"Check on the re-keyed panels only ({len(newrows)} seeds): rho {spearman([r['ck2'] for r in newrows], [r['pm'] for r in newrows]):.3f}.")
    text = "\n".join(L) + "\n"
    (OUT / "E16F6_SIGNATURE.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
