import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import exp26_candidate as C          # noqa: E402  (imports exp20_reference, which applies the environment gate)
import torch as T                    # noqa: E402
import arch26                        # noqa: E402
import e40_new_family as E40         # noqa: E402
import e48_gated as G                # noqa: E402

E, X, X16, R = C.E, C.X, C.X16, C.R
OUT = HERE / "exp45" / "e48"
SPEC = HERE.parent / "PROJECT_DOCUMENTS" / "COORD_CHECKS_20261116" / "e48_gated_spec.py"
ROWS = (0, 16, 32, 64, 128, 256, 512, 1024)
ANSWER_ROWS = (0, 64, 128, 256, 512, 1024)        # the reduction score's generated bytes are written at these rows
TERM_ROWS_ALL = (128, 256, 512, 1024)             # term files at every rank
TERM_ROWS_EARLY = (16, 32, 64)                    # and at ranks 4 and 16 only
FORCED_OFF_ROWS = (256, 1024)
RANKS = (4, 16, 64)
SEEDS = E40.SEEDS
OWN = ("exp48_gated_run.py", "e48_gated.py", "e40_new_family.py")
EARLIER6 = E40.EARLIER6

# ---------------------------------------------------------------- the gate, installed
STATE = dict(term=None, force_off=False, calls=0, on_calls=0)


def gate_of(x):
    g = (x[:, 1] >= G.CODES[0]) & (x[:, 1] <= G.CODES[-1])
    on = bool(g[0])
    assert bool((g == on).all()), "the rows of one call disagree on the gate"
    return on


def gated_forward(m, x, local, through_time, keep=False, silence=False):
    """The harness's signature; returns e48_gated.forward(m, term, x, local, gate, silence)."""
    assert through_time, "E48's forward runs through time only"
    gate = gate_of(x) and not STATE["force_off"]
    STATE["calls"] += 1; STATE["on_calls"] += gate
    return G.forward(m, STATE["term"], x, local, gate, silence)


# a recorder of what respond generates, so that the answers can be written without touching E40's Scorer
_RESPOND = E.respond
LOG = []


def recording_respond(m, prompts, store=None, cap=4, silence=False):
    out = _RESPOND(m, prompts, store, cap, silence)
    LOG.append(([list(p) for p in prompts], out))
    return out


def install():
    arch26.install()
    E.forward = gated_forward
    E.respond = recording_respond


def step(m, term, opt, items, local, grads=None):
    """exp26_candidate.step's text, with the installed gated forward and keep_code_rows between backward and opt.step."""
    x, y, mask = X.batch_tensor(items)
    logits = E.forward(m, x, local, True)[0]
    loss = E.cross_entropy(logits[mask], y[mask])
    opt.zero_grad()
    loss.backward()
    G.keep_code_rows(m)
    if grads is not None:
        grads.append({k: float(getattr(term, k).grad.abs().max()) for k in ("up_i", "down_i", "up_h", "down_h")})
    opt.step()
    return float(loss.detach())


# ---------------------------------------------------------------- scoring with the answers kept
def scorer_order(sc):
    """The order in which E40's Scorer calls X16.score (one task per call)."""
    o = [("held_k12", n, it) for n, it in sc.held.items()] + [("taught_k12", n, it) for n, it in sc.taught.items()]
    o += [("held_plain_k0", f"{n}/{w}", it) for n, v in sc.plain.items() for w, it in v.items()]
    o += [("earlier_k12", n, sc.P[n][12]) for n in EARLIER6]
    return o


def score(sc, m):
    LOG.clear()
    s = sc(m)
    order = scorer_order(sc)
    assert len(LOG) == len(order), (len(LOG), len(order))
    answers = {}
    for (kind, name, items), (prompts, outs) in zip(order, LOG):
        assert prompts == [list(p) for p, _ in items], f"recorder out of step at {kind} {name}"
        answers[(kind, name)] = (items, outs)
    LOG.clear()
    return s, answers


def sha_json(obj):
    return hashlib.sha256(json.dumps(obj, separators=(",", ":")).encode()).hexdigest()


def earlier_digests(answers):
    per = {n: sha_json(answers[("earlier_k12", n)][1]) for n in EARLIER6}
    return dict(per_panel=per, all=sha_json([answers[("earlier_k12", n)][1] for n in EARLIER6]))


def reduction_answers(answers):
    return {n: answers[("held_plain_k0", f"{n}/reduction")][1] for n in ("add83", "sub83")}


def reduction_prompts(answers):
    return {n: [[list(p), list(t)] for p, t in answers[("held_plain_k0", f"{n}/reduction")][0]] for n in ("add83", "sub83")}


def cosines(term):
    """The cosine between each factor and what the sweep uses in its place: sign(F) * mean|F| (exp3_state.SignLinear)."""
    res = {}
    for k in ("down_i", "up_i", "down_h", "up_h"):
        F = getattr(term, k).detach().double().flatten()
        S = F.sign() * F.abs().mean()
        res[k] = None if float(F.norm()) == 0.0 else float(T.nn.functional.cosine_similarity(F, S, dim=0))
    return res


def term_tensors(m, term):
    return dict(up_i=term.up_i.detach().clone(), down_i=term.down_i.detach().clone(), up_h=term.up_h.detach().clone(),
                down_h=term.down_h.detach().clone(), code_rows=m.book.weight.detach()[list(G.CODES)].clone())


def save_term(m, term, path):
    d = term_tensors(m, term)
    assert all(v.dtype == T.float32 and not isinstance(v, T.nn.Parameter) and not v.requires_grad for v in d.values())
    tmp = Path(str(path) + ".tmp"); T.save(d, tmp); tmp.replace(path)
    return X16.sha_file(path), R.tensors_sha(d)


def lived_sha_with_codes_reset(m, start_rows):
    sd = {k: v.detach().clone() for k, v in m.state_dict().items()}
    sd["book.weight"][list(G.CODES)] = start_rows
    return R.tensors_sha(sd)


def e40_receipt(rule, seed):
    return json.loads((HERE / "exp45" / "e40" / f"e40_lived_{rule}_{seed}.json").read_text())


def provenance(cmd):
    p = C.provenance(cmd)
    p["e48_sources_sha256"] = {s: X16.sha_file(HERE / s) for s in OWN}
    p["e48_spec_sha256"] = X16.sha_file(SPEC)
    p["e48_gated_is_spec"] = (HERE / "e48_gated.py").read_bytes() == SPEC.read_bytes()
    return p


# ---------------------------------------------------------------- one run
def run(rule, seed, rank, updates, out, cmd):
    install()
    out = Path(out)
    name = f"e48_{rule}_{seed}_r{rank}"
    rows = [r for r in ROWS if r <= updates]
    if updates not in rows:
        rows.append(updates)
    term_rows = [r for r in rows if r in TERM_ROWS_ALL or (r in TERM_ROWS_EARLY and rank in (4, 16))]
    rec_path, ans_path = out / f"{name}.json", out / f"{name}_reduction_answers.json"
    tpaths = {r: out / f"{name}_row{r}.pt" for r in term_rows}
    R.refuse_existing(rec_path, ans_path, *tpaths.values(), *[str(p) + ".tmp" for p in tpaths.values()])
    out.mkdir(parents=True, exist_ok=True)
    local = rule == "S"
    T.manual_seed(seed)
    m, _, info = E40.start("lived", rule, seed)
    assert info["tensors_sha_matches_receipt"]
    start_codes = m.book.weight.detach()[list(G.CODES)].clone()
    term = G.Term(seed, rank); STATE["term"] = term; STATE["force_off"] = False
    G.freeze(m); opt = G.make_opt(m, term)
    e40 = e40_receipt(rule, seed); e40_rows = {r["updates"]: r for r in e40["rows"]}
    e40_row0_earlier = {n: e40_rows[0]["scores"]["earlier_k12"][n]["exact"] for n in EARLIER6}
    sc = E40.Scorer(seed)
    bt = E40.batches(seed)
    dg = C.Digest(); pr = E40.Presented(seed)
    rec = dict(experiment="E48", rule=rule, seed=seed, rank=rank, updates=updates, rows_planned=rows, start=info,
               numbers_that_may_change=term.count(), network_parameters=sum(q.numel() for q in m.parameters()),
               trainable=[n for n, q in m.named_parameters() if q.requires_grad] + ["term.down_i", "term.up_i", "term.down_h", "term.up_h"],
               optimizer=dict(kind="AdamW", lr=0.001, betas=[0.9, 0.98], groups=[dict(params="term (4 factors)", weight_decay=0.25), dict(params="book.weight", weight_decay=0.0)]),
               data="E40: 64 consecutive items of X16.entry_stream(F4 taught tenth, seed + 140) (e40_new_family.batches)",
               update=f"exp48_gated_run.step (exp26_candidate.step's text; e48_gated.forward with the gate; keep_code_rows; local={local})",
               gate="on iff x[:, 1] in 101..104, asserted equal for all rows of a call",
               provenance=provenance(cmd), rows=[], complete=False)
    answers_file = dict(experiment="E48", run=name, rows={}, prompts=None)
    t0 = time.process_time(); cpu_score = 0.0; losses = []; u = 0; grads = []
    row0_digest = None
    for r in rows:
        while u < r:
            items = next(bt); dg.add(items); pr.add(items)
            losses.append(step(m, term, opt, items, local, grads if u < 2 else None)); u += 1
        cb = time.process_time()
        s, ans = score(sc, m)
        ed = earlier_digests(ans)
        forced = None
        if r in FORCED_OFF_ROWS:
            STATE["force_off"] = True
            sf, _ = score(sc, m)
            STATE["force_off"] = False
            forced = dict(held_k12=sf["held_k12"], taught_k12=sf["taught_k12"], held_plain_k0=sf["held_plain_k0"], summary=sf["summary"],
                          earlier_k12=sf["earlier_k12"])
        cpu_score += time.process_time() - cb
        if r == 0:
            row0_digest = ed["all"]
            answers_file["prompts"] = reduction_prompts(ans)
        if r in ANSWER_ROWS:
            answers_file["rows"][str(r)] = reduction_answers(ans)
        earlier_counts = {n: s["earlier_k12"][n]["exact"] for n in EARLIER6}
        row = dict(updates=r, scores=s, scores_gate_forced_off=forced,
                   loss_since_last_row=(sum(losses) / len(losses)) if losses else None,
                   finite_losses=all(v == v and abs(v) != float("inf") for v in losses), data_digest=dg.value(), presented=pr.value(),
                   earlier_answers_sha256=ed,
                   check3=dict(earlier_digest_equals_row0=ed["all"] == row0_digest, earlier_counts=earlier_counts,
                               earlier_counts_equal_e40_row0=earlier_counts == e40_row0_earlier,
                               lived_tensors_sha256_codes_reset=lived_sha_with_codes_reset(m, start_codes),
                               equals_life_end=lived_sha_with_codes_reset(m, start_codes) == info["receipt_tensors_sha256"]),
                   check4=dict(e40_data_digest=e40_rows[r]["data_digest"]["sha256"] if r in e40_rows else None,
                               equal=(dg.value()["sha256"] == e40_rows[r]["data_digest"]["sha256"]) if r in e40_rows else None),
                   code_rows_tensors_sha256=R.tensors_sha({"code_rows": m.book.weight.detach()[list(G.CODES)]}),
                   term_norms={k: float(getattr(term, k).detach().norm()) for k in ("down_i", "up_i", "down_h", "up_h")},
                   sweep_cosines=cosines(term) if local else None,
                   optimizer_steps=R.opt_steps(opt), cpu=time.process_time() - t0, cpu_scoring_so_far=cpu_score)
        if r == 0:
            row["check2"] = dict(scores_equal_e40_row0=s == e40_rows[0]["scores"])
        if r in tpaths:
            fsha, tsha = save_term(m, term, tpaths[r])
            row["term_file"] = dict(file=tpaths[r].name, sha256=fsha, tensors_sha256=tsha, bytes=tpaths[r].stat().st_size)
        if len(grads) >= 2:
            rec["grads_updates_1_2"] = grads[:2]
        losses = []
        rec["rows"].append(row)
        sm = s["summary"]
        print(name, r, f"held {sm['held_add_sub_mean']:.1f} taught {sm['taught_add_sub_mean']:.1f} red {sm['reduction_score']:.1f} nored {sm['no_reduction_score']:.1f}",
              f"earlier-same {row['check3']['earlier_digest_equals_row0']} lived-same {row['check3']['equals_life_end']}",
              f"digest {row['check4']['equal']}", f"cpu {row['cpu']:.0f}s", flush=True)
        X16.write_json(rec_path, rec)
    assert pr.held_hits == 0 and pr.not_taught == 0 and pr.earlier_codes == 0, pr.value()
    rec["gate_calls"] = dict(calls=STATE["calls"], gate_on=STATE["on_calls"])
    rec.update(complete=True, cpu_total=time.process_time() - t0, cpu_scoring=cpu_score, cpu_updates=time.process_time() - t0 - cpu_score)
    X16.write_json(rec_path, rec)
    tmp = Path(str(ans_path) + ".tmp"); tmp.write_text(json.dumps(answers_file, separators=(",", ":"))); tmp.replace(ans_path)
    rec["reduction_answers_file"] = dict(file=ans_path.name, sha256=X16.sha_file(ans_path))
    X16.write_json(rec_path, rec)
    print(name, "complete", flush=True)
    return m, term


# ---------------------------------------------------------------- checks
def check1():
    """The specification file: the copy is byte-identical; run on $K (python3 -I), its self-checks print what OUTPUT_E48_SPEC_MAC.txt has."""
    import subprocess
    identical = (HERE / "e48_gated.py").read_bytes() == SPEC.read_bytes()
    import os
    env = {k: v for k, v in os.environ.items() if not k.startswith(("E11_", "E16_"))}   # as from a shell: the parent's import set these
    p = subprocess.run([sys.executable, "-I", SPEC.name], cwd=SPEC.parent, capture_output=True, text=True, env=env)
    want = (SPEC.parent / "OUTPUT_E48_SPEC_MAC.txt").read_text()
    return dict(identical=identical, spec_sha256=X16.sha_file(SPEC), copy_sha256=X16.sha_file(HERE / "e48_gated.py"), returncode=p.returncode,
                stdout=p.stdout, stderr=p.stderr, stdout_equals_mac_output_exactly=p.stdout == want,
                ok=identical and p.returncode == 0 and p.stdout == want)


def check2():
    """Row 0 through the installed forward (rank 16 term, up at zero) equals E40's row 0 on every score, for each of the six networks."""
    install(); res = {}
    for seed in SEEDS:
        sc = E40.Scorer(seed)
        for rule in ("S", "B"):
            m, _, info = E40.start("lived", rule, seed)
            STATE["term"] = G.Term(seed, 16)
            s, _ = score(sc, m)
            want = e40_receipt(rule, seed)["rows"][0]["scores"]
            diff = [k for k in want if s[k] != want[k]]
            res[f"{rule}_{seed}"] = dict(equal=s == want, differing=diff, reduction_score=s["summary"]["reduction_score"], ok=s == want)
            print("check2", rule, seed, s == want, flush=True)
    return dict(rows=res, ok=all(v["ok"] for v in res.values()))


def check3(d):
    """From the receipts: at every row the earlier panels' answer digest equals row 0's, the six counts equal E40's row 0, and the lived
    tensors with the code rows reset equal the life-end file's tensors_sha256."""
    res = {}
    for p in sorted(Path(d).glob("e48_*_r*.json")):
        if p.name.endswith("_reduction_answers.json"):
            continue
        r = json.loads(p.read_text())
        rows = {row["updates"]: dict(digest=row["check3"]["earlier_digest_equals_row0"], counts=row["check3"]["earlier_counts_equal_e40_row0"],
                                     lived=row["check3"]["equals_life_end"]) for row in r["rows"]}
        res[p.stem] = dict(complete=r["complete"], rows=rows, ok=r["complete"] and all(all(v.values()) for v in rows.values()))
    return dict(runs=res, n=len(res), ok=bool(res) and all(v["ok"] for v in res.values()))


def check4(d):
    """From the receipts: the batch digest at rows 64..1024 equals E40's for the seed; rows 16 and 32 recorded."""
    res = {}
    for p in sorted(Path(d).glob("e48_*_r*.json")):
        if p.name.endswith("_reduction_answers.json"):
            continue
        r = json.loads(p.read_text())
        rows = {row["updates"]: dict(sha256=row["data_digest"]["sha256"], e40=row["check4"]["e40_data_digest"], equal=row["check4"]["equal"]) for row in r["rows"]}
        res[p.stem] = dict(rows=rows, ok=all(v["equal"] for u, v in rows.items() if u in (64, 128, 256, 512, 1024)) and
                           all(u in rows for u in (64, 128, 256, 512, 1024) if u <= r["updates"]))
    return dict(runs=res, ok=bool(res) and all(v["ok"] for v in res.values()))


def check3a5(rule, seed=73129, rank=16):
    """Check 5 (at update 2 the gradient of both down matrices is not zero) and check 3a (at row 64, through the installed forward, an
    earlier family's logits equal arch26.forward's on the same network; the new family's do not), re-running the dry run's 64 updates in memory."""
    install(); local = rule == "S"
    T.manual_seed(seed)
    m, _, info = E40.start("lived", rule, seed)
    term = G.Term(seed, rank); STATE["term"] = term; STATE["force_off"] = False
    G.freeze(m); opt = G.make_opt(m, term)
    bt = E40.batches(seed); grads = []
    for u in range(64):
        step(m, term, opt, next(bt), local, grads if u < 2 else None)
    res = dict(check5=dict(update1=grads[0], update2=grads[1],
                           ok=grads[1]["down_i"] > 0 and grads[1]["down_h"] > 0 and grads[0]["down_i"] == 0 and grads[0]["down_h"] == 0))
    old_dev = next(E.batches([(t, E.split(t, .5, seed)[0]) for t in E.DEV], seed, 12))
    sc = E40.Scorer(seed)
    old_97 = sc.P["add97"][12][:64]
    new = next(E40.batches(seed + 1))
    cmp = {}
    with T.no_grad():
        for nm, items in (("earlier_dev_batch", old_dev), ("earlier_add97_k12", old_97), ("new_family_batch", new)):
            x = X.batch_tensor(items)[0]
            a = E.forward(m, x, local, True)[0]; b = arch26.forward(m, x, local, True)[0]
            cmp[nm] = dict(gate=gate_of(x), bit_equal=bool(T.equal(a, b)), max_abs_diff=float((a - b).abs().max()))
    res["check3a"] = dict(row=64, comparisons=cmp, ok=cmp["earlier_dev_batch"]["bit_equal"] and cmp["earlier_add97_k12"]["bit_equal"]
                          and not cmp["new_family_batch"]["bit_equal"])
    res["ok"] = res["check5"]["ok"] and res["check3a"]["ok"]
    return res


if __name__ == "__main__":
    T.set_num_threads(1)
    a = sys.argv[1:]
    cmd = " ".join([Path(sys.executable).name, Path(__file__).name, *a])

    def opt_(flag, default=None):
        return a[a.index(flag) + 1] if flag in a else default

    out = Path(opt_("--out", str(OUT)))
    if a[0] == "run":
        assert a[1] in ("S", "B") and int(a[3]) in RANKS
        run(a[1], int(a[2]), int(a[3]), int(opt_("--updates", "1024")), out, cmd)
    elif a[0] == "check":
        t0 = time.process_time(); part = a[1]
        if part == "1":
            res = check1(); name = "check1"
        elif part == "2":
            res = check2(); name = "check2"
        elif part == "3":
            res = check3(opt_("--runs", str(OUT))); name = "check3"
        elif part == "4":
            res = check4(opt_("--runs", str(OUT))); name = "check4"
        elif part == "3a5":
            res = check3a5(a[2]); name = f"check3a_check5_{a[2]}"
        else:
            raise SystemExit(__doc__)
        p = out / "checks" / f"E48_{name}.json"
        R.refuse_existing(p); p.parent.mkdir(parents=True, exist_ok=True)
        X16.write_json(p, dict(check=name, command=cmd, provenance=provenance(cmd), cpu_seconds=time.process_time() - t0, result=res))
        print(name, "pass" if res.get("ok") else "FAIL", f"cpu {time.process_time() - t0:.0f}s", flush=True)
    else:
        raise SystemExit(__doc__)
