"""E48 runner (brief OPUS_TASK_E48_A_NEW_FAMILY_IN_CONNECTIONS_GATED_BY_ITS_CODE_20261116.md, revision 2): a new family (E40's F4, mod 83,
codes e f g h) learned only in two added terms of rank r on the recurrent layer's two matrices and the four code rows of the byte table,
switched on by a gate the harness reads from the item's code byte. Every parameter of the lived network is frozen. A new file; every
existing source stays as it is. The specification is e48_gated.py (a byte-identical copy of
PROJECT_DOCUMENTS/COORD_CHECKS_20261116/e48_gated_spec.py), imported, not rewritten. E40's stream, panels and Scorer are imported from
e40_new_family.py unchanged.

    python3 exp48_gated_run.py run <S|B> <seed> <rank> [--updates N] [--out DIR]
    python3 exp48_gated_run.py check <1|2|3|4|5> [--out DIR]       (3 and 4 read the run receipts in DIR; 3a and 5 come from the dry runs)
    python3 exp48_gated_run.py check 3a5 <S|B> [--out DIR]           (check 3a and check 5 on the dry run's start and its row 64)

The gate: on for an item iff x[:, 1] (the byte after the start symbol) is one of 101..104, asserted equal for every row of a call, held for
every position. After arch26.install() exp11_cell.forward is replaced by gated_forward, so that E40's Scorer and exp11_cell.respond run
unchanged. The update is exp26_candidate.step's text with this forward in place of arch26.forward and keep_code_rows(m) between backward
and opt.step(); freeze(m) once, before make_opt.
"""
