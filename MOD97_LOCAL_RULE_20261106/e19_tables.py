"""E19 tables (read-only): birth curves of kbank2 by backprop (bptt), forward-only rule with weight signs (r1) and without deep traces (r2).
Writes exp45/SUMMARY_E19.md."""
import json
from pathlib import Path
OUT = Path(__file__).resolve().parent / "exp45"
SEEDS, ARMS, OPS, KS = (73129, 93683, 116089), ("bptt", "r1", "r2"), ("add89", "sub89", "max89", "min89"), ("0", "4", "8", "12", "20")
REF = {73129: 91.2, 93683: 94.5, 116089: 90.3}
pc = lambda v: 100 * v["exact"] / v["n"]
L = ["# SUMMARY_E19: kbank2 births", "", "Generated by `e19_tables.py`. Exact answers (%) on the sealed development panels (300 items each). "
     "Hard mean = mean of add89 and sub89 at k = 12. Reference (owner's machine): existing two-bank network by backprop, hard mean 91.2 / 94.5 / 90.3.", ""]
fin = {}
for a in ARMS:
    for s in SEEDS:
        r = json.loads((OUT / f"e19_dev_kbank2_{a}_{s}.json").read_text())
        L += [f"## {a}, seed {s}", "", "| updates | " + " | ".join(f"{o} k={k}" for o in OPS for k in KS) + " | hard mean | loss | CPU s |",
              "|---:|" + "---:|" * (len(OPS) * len(KS) + 3)]
        for c in r["curve"]:
            sc = c["sealed"]
            L.append(f"| {c['step']} | " + " | ".join(f"{pc(sc[o][k]):.1f}" for o in OPS for k in KS)
                     + f" | {(pc(sc['add89']['12']) + pc(sc['sub89']['12'])) / 2:.1f} | {c['loss']:.3f} | {c['cpu']:.0f} |")
        c = r["curve"][-1]
        L += ["", f"Silenced (both banks zero in the readout), k = 12: " + ", ".join(f"{o} {pc(c['silenced_k12'][o]):.1f}" for o in OPS)
              + f". CPU ms per update {c['cpu_ms_per_update']:.1f}; peak RSS {r['peak_rss_kb'] // 1024} MB; parameters {r['n_params']:,}.", ""]
        fin[(a, s)] = (pc(c["sealed"]["add89"]["12"]) + pc(c["sealed"]["sub89"]["12"])) / 2
L += ["## Final hard means", "", "| seed | reference | bptt | r1 | r2 | r1 / bptt | r1 − r2 |", "|---|---:|---:|---:|---:|---:|---:|"]
for s in SEEDS:
    L.append(f"| {s} | {REF[s]} | {fin[('bptt', s)]:.1f} | {fin[('r1', s)]:.1f} | {fin[('r2', s)]:.1f} | {fin[('r1', s)] / fin[('bptt', s)]:.3f} | {fin[('r1', s)] - fin[('r2', s)]:+.1f} |")
(OUT / "SUMMARY_E19.md").write_text("\n".join(L) + "\n")
print("\n".join(L[-6:]))
