"""E16-F7: the pre-registered signature S over the eighteen drift seeds (reads only). Adapted from e16f6_signature.py.

S = the learner's lowest mod-97 family mean at k = 12 over checkpoints 2, 3 and 4.

For each seed with a finished drift learner life (`T_raw65536_drift_online`) and its drift twin (`D_drift`): the learner's
S, its `+-` and `-+` pairs by final answer at checkpoint 6, its ratios to the twin on the
three families at checkpoint 6. Sorted by S; Spearman rank correlation (average ranks for ties) between S and the final `+-`;
the threshold clauses of P16F7.4 (S < 65 -> composition ratio < 0.80; S >= 70 -> >= 0.80). Writes exp45/SIGNATURE_E16F7.md.
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
SEEDS = (73129, 93683, 116089, 200003, 300007, 400009, 500011, 600013, 700027, 800011, 900007, 1000003,
         1100009, 1200007, 1300021, 1400017, 1500007, 1600033)
NEW = SEEDS[12:]
SOURCE = {73129: "E16-S", 93683: "E16-S", 116089: "E16-S", 200003: "E16-F5", 300007: "E16-F5", 400009: "E16-F5",
          500011: "E16-F6", 600013: "E16-F6", 700027: "E16-F6", 800011: "E16-F6", 900007: "E16-F6", 1000003: "E16-F6"}
F1 = ("add97", "sub97", "max97", "min97")
F3 = ("add73", "sub73", "max73", "min73")
HELD = ("+-", "-+", "><", "<>")


def op(sc, n):
    return 100 * sc[n]["12"]["exact"] / sc[n]["12"]["n"]


def pair(sc, h):
    c = sc["compose"][h]
    return 100 * c["final"] / c["n"]


def fam(sc):
    return (sum(op(sc, n) for n in F1) / 4, sum(pair(sc, h) for h in HELD) / 4, sum(op(sc, n) for n in F3) / 4)


def load(tag, seed):
    p = OUT / f"e16_life_{tag}_{seed}.json"
    return json.load(open(p))["stages"] if p.exists() else None


def ranks(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    r = [0.0] * len(xs)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for k in range(i, j + 1):
            r[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return r


def spearman(x, y):
    rx, ry = ranks(x), ranks(y)
    mx, my = sum(rx) / len(rx), sum(ry) / len(ry)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    den = (sum((a - mx) ** 2 for a in rx) * sum((b - my) ** 2 for b in ry)) ** 0.5
    return num / den


def main():
    rows, missing = [], []
    for s in SEEDS:
        t, d = load("T_raw65536_drift_online", s), load("D_drift", s)
        if not t or not d or len(t) < 7 or len(d) < 7:
            missing.append(s); continue
        c2 = min(fam(t[i]["scores"])[0] for i in (2, 3, 4))
        sc, scd = t[6]["scores"], d[6]["scores"]
        ratio = [a / b for a, b in zip(fam(sc), fam(scd))]
        rows.append((c2, s, pair(sc, "+-"), pair(sc, "-+"), ratio, [fam(t[i]["scores"])[0] for i in (2, 3, 4)]))
    rows.sort()
    L = ["# SIGNATURE_E16F7: the pre-registered signature S over the drift seeds", "",
         "Generated by `e16f7_signature.py` (reads only). Learner `T_raw65536_drift_online`, twin `D_drift`. S is the "
         "learner's lowest mod-97 family mean at k = 12 over checkpoints 2, 3 and 4; `+-` and `-+` are final-answer "
         "accuracy (%) at checkpoint 6; ratios are the learner's family means over the twin's at checkpoint 6 "
         "(mod-97 ops · held comp · mod-73 ops).", "",
         "| Seed | Source | S | mod-97 at ckpt 2 / 3 / 4 | Final `+-` | Final `-+` | Ratios to twin | Comp ratio ≥ 0.80 | All three ≥ 0.80 |",
         "|---:|---|---:|---|---:|---:|---|---|---|"]
    for S, s, pm, mp, r, c in rows:
        L.append(f"| {s} | {SOURCE.get(s, 'E16-F7')} | {S:.1f} | " + " / ".join(f"{x:.1f}" for x in c) + f" | {pm:.1f} | {mp:.1f} | "
                 + " · ".join(f"{x:.2f}" for x in r) + f" | {'yes' if r[1] >= 0.80 else '**no**'} | {'yes' if min(r) >= 0.80 else '**no**'} |")
    L.append("")
    if len(rows) >= 3:
        rho = spearman([r[0] for r in rows], [r[2] for r in rows])
        low = [(s, r[1]) for S, s, pm, mp, r, c in rows if S < 65]
        high = [(s, r[1]) for S, s, pm, mp, r, c in rows if S >= 70]
        okl, okh = all(x < 0.80 for _, x in low), all(x >= 0.80 for _, x in high)
        L += [f"Seeds: {len(rows)}. Spearman rank correlation, S against final `+-`: **{rho:.3f}** (clause: at least 0.35; "
              f"{'holds' if rho >= 0.35 else 'misses'}).", "",
              f"- S below 65: {', '.join(f'{s} (comp ratio {x:.2f})' for s, x in low) or 'none'}; every one below 0.80 on "
              f"compositions: {'holds' if okl else '**misses**'}.",
              f"- S at or above 70: {', '.join(f'{s} ({x:.2f})' for s, x in high) or 'none'}; every one at or above 0.80: "
              f"{'holds' if okh else '**misses**'}" + ("" if okh else f" (below: {', '.join(f'{s} {x:.2f}' for s, x in high if x < 0.80)})") + ".",
              f"- S from 65 to below 70 (no clause): {', '.join(f'{s} ({r[1]:.2f})' for S, s, pm, mp, r, c in rows if 65 <= S < 70) or 'none'}.",
              "", f"P16F7.4 (both clauses must hold): **{'holds' if rho >= 0.35 and okl and okh else 'misses'}**."]
    if missing:
        L += ["", f"Not yet finished (excluded): {', '.join(map(str, missing))}."]
    L += ["", "## Every checkpoint, this job's six seeds: mod-97 operations (k = 12) and held pairs (final answer)", ""]
    for s in NEW:
        L += [f"### Seed {s}", "", "| Arm | Ckpt | add97 | sub97 | max97 | min97 | mod-97 mean | +- | -+ | >< | <> | held mean | mod-73 mean |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for lab, tag in (("learner", "T_raw65536_drift_online"), ("twin", "D_drift")):
            for i, x in enumerate(load(tag, s) or []):
                sc = x["scores"]; v = fam(sc)
                L.append(f"| {lab} | {i} | " + " | ".join(f"{op(sc, n):.1f}" for n in F1) + f" | {v[0]:.1f} | "
                         + " | ".join(f"{pair(sc, h):.1f}" for h in HELD) + f" | {v[1]:.1f} | {v[2]:.1f} |")
        L.append("")
    (OUT / "SIGNATURE_E16F7.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
