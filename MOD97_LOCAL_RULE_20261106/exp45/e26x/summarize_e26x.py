"""E26-X: verify the six crossed lives and read the 2 x 2 (birth x later update) as fixed in E26X_DESIGN.md.
Diagonal cells are the E26 lives (exp45/e26/e26_life_<arm>_<seed>.json). Reads only. Run from MOD97_LOCAL_RULE_20261106.
Writes exp45/e26x/E26X_RESULTS.json and E26X_RESULTS.md."""
import hashlib, json, subprocess, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent; MOD = HERE.parent.parent
sys.path.insert(0, str(MOD))
import torch as T
import exp20_reference as R
import exp16_integrated as X16
import exp26_candidate as C

SEEDS = (73129, 93683, 116089); HELD = ("+-", "-+", "><", "<>"); CELLS = ("SS", "SB", "BS", "BB")
pct = lambda d: 100.0 * d["exact"] / d["n"]
pinned = {f: hashlib.sha256(subprocess.run(["git", "show", f"360e1b8d:MOD97_LOCAL_RULE_20261106/{f}"], cwd=MOD, capture_output=True, check=True).stdout).hexdigest() for f in C.SOURCES}
E26 = MOD / "exp45" / "e26"
def path(c, s):
    return (E26 / f"e26_life_{c[0]}_{s}.json") if c[0] == c[1] else (HERE / f"e26x_life_{c}_{s}.json")
out = dict(checks={}, cells={})
for s in SEEDS:
    digests = {}
    for c in CELLS:
        j = path(c, s); r = json.loads(j.read_text()); cp = r["complete"]; st0 = r["stages"][0]["settings"]
        bsha = json.loads((E26 / f"e26_dev_{c[0]}_{s}.json").read_text())["weights_sha256"]
        ck = dict(complete=isinstance(cp, dict) and cp.get("stages") == 7, steps=cp["optimizer_steps"] == [36864],
                  birth_ok=st0["birth_sha256"] == bsha, update_ok=r["local"] == (c[1] == "S"),
                  sources_ok=st0["provenance"]["sources_sha256"] == pinned, finite=all(x["finite_losses"] for x in r["stages"][1:]),
                  no_held_presented=all(x["exposure_panels"]["within_or_held_presented"] == 0 for x in r["stages"][1:]))
        if c[0] != c[1]:
            p = j.with_suffix(".pt")
            ck.update(weights_ok=X16.sha_file(p) == cp["weights_sha256"], tensors_ok=R.tensors_sha(T.load(p)) == cp["tensors_sha256"],
                      crossover_ok=st0["provenance"].get("crossover", {}).get("birth_arm") == c[0] and st0["provenance"]["crossover"]["update_arm"] == c[1])
        out["checks"][f"{c}_{s}"] = ck
        digests[c] = cp["data_digest"]["sha256"]
        rows = []
        for x in r["stages"]:
            cpz = x["scores"]["compose"]
            rows.append(dict(stage=int(x["stage"]), within=pct(cpz["within"]), held={h: pct(cpz[h]) for h in HELD},
                             pm=100.0 * (cpz["+-"]["exact"] + cpz["-+"]["exact"]) / (cpz["+-"]["n"] + cpz["-+"]["n"]), taught=pct(x["scores"]["taught"])))
        out["cells"][f"{c}_{s}"] = dict(rows=rows, cpu_total=cp["cpu_total"])
    out["checks"][f"same_data_{s}"] = len(set(digests.values())) == 1
out["all_checks_pass"] = all((v if isinstance(v, bool) else all(v.values())) for v in out["checks"].values())
end = lambda c, s, k, st=6: out["cells"][f"{c}_{s}"]["rows"][st][k]
def effect(a, b, k="pm", st=6):   # a minus b, seed by seed
    d = [end(a, s, k, st) - end(b, s, k, st) for s in SEEDS]
    return dict(per_seed=d, mean=sum(d) / 3, present=sum(x >= 5 for x in d) >= 2 and sum(d) / 3 >= 5)
E = dict(update_effect_birth_S=effect("SB", "SS"), update_effect_birth_B=effect("BB", "BS"),
         birth_effect_update_S=effect("BS", "SS"), birth_effect_update_B=effect("BB", "SB"))
u = E["update_effect_birth_S"]["present"] and E["update_effect_birth_B"]["present"]
b = E["birth_effect_update_S"]["present"] and E["birth_effect_update_B"]["present"]
out["effects_plus_minus_end"] = E
out["effects_within_end"] = dict(update_effect_birth_S=effect("SB", "SS", "within"), update_effect_birth_B=effect("BB", "BS", "within"),
                                 birth_effect_update_S=effect("BS", "SS", "within"), birth_effect_update_B=effect("BB", "SB", "within"))
out["effects_plus_minus_stage3"] = dict(update_effect_birth_S=effect("SB", "SS", "pm", 3), update_effect_birth_B=effect("BB", "BS", "pm", 3),
                                        birth_effect_update_S=effect("BS", "SS", "pm", 3), birth_effect_update_B=effect("BB", "SB", "pm", 3))
out["reading"] = ("update carries the gap" if u and not b else "birth carries the gap" if b and not u else
                  "both update and birth effects present" if u and b else "interaction / neither effect present in both conditions")
out["joint_pass"] = {c: [s for s in SEEDS if end(c, s, "within") >= 85 and end(c, s, "pm") >= 40] for c in CELLS}
(HERE / "E26X_RESULTS.json").write_text(json.dumps(out, indent=1))
L = ["# E26-X results: birth weights x later update", "", "Generated by summarize_e26x.py. Percent whole answers. Cell XY = birth X, update Y; SS and BB are the E26 lives.", "",
     f"**All checks pass:** {out['all_checks_pass']}", "", f"**Reading (as fixed in E26X_DESIGN.md):** {out['reading']}", "",
     "## End of life (stage 6): within / plus-minus", "", "| seed | SS | SB | BS | BB |", "|---|---|---|---|---|"]
L += [f"| {s} | " + " | ".join(f"{end(c, s, 'within'):.1f} / {end(c, s, 'pm'):.1f}" for c in CELLS) + " |" for s in SEEDS]
L += ["", "Joint passes (within >= 85 and plus-minus >= 40): " + ", ".join(f"{c} {len(v)}/3 {v}" for c, v in out["joint_pass"].items()), ""]
for title, key in (("Effects on plus-minus, end of life", "effects_plus_minus_end"), ("Effects on within, end of life", "effects_within_end"),
                   ("Effects on plus-minus, stage 3 (F2.1)", "effects_plus_minus_stage3")):
    L += [f"## {title}", "", "| effect | 73129 | 93683 | 116089 | mean | present |", "|---|---|---|---|---|---|"]
    L += [f"| {k} | " + " | ".join(f"{x:+.1f}" for x in v["per_seed"]) + f" | {v['mean']:+.1f} | {v['present']} |" for k, v in out[key].items()]
    L.append("")
L += ["## Checkpoints (stages 3 to 6): within / plus-minus / +- / -+ / >< / <>", "", "| cell | seed | stage | within | pm | +- | -+ | >< | <> |", "|" + "---|" * 9]
for s in SEEDS:
    for c in CELLS:
        for r in out["cells"][f"{c}_{s}"]["rows"][3:]:
            L.append(f"| {c} | {s} | {r['stage']} | {r['within']:.1f} | {r['pm']:.1f} | " + " | ".join(f"{r['held'][h]:.1f}" for h in HELD) + " |")
L += ["", "## Checks", ""] + [f"- {k}: {v}" for k, v in out["checks"].items()]
L += ["", "## CPU seconds (crossed lives)", ""] + [f"- {c} {s}: {out['cells'][f'{c}_{s}']['cpu_total']:.0f}" for s in SEEDS for c in ("SB", "BS")]
(HERE / "E26X_RESULTS.md").write_text("\n".join(L) + "\n"); print("\n".join(L))
