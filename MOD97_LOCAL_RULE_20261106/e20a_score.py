"""E20-A: tables and verdicts from the receipts (reads only; writes exp45/E20A_TABLES.md).

Arms (brief OPUS_TASK_E20_COMPOSITION_FROM_MEMORY_20261110.md, Job A v2), all E16_COMPGAP=6:
  Dw  window reference          exp45/e16_life_D_cm6_<seed>.json
  T   window learner, sign rule exp45/e16_life_T_raw65536_cm6_<seed>.json
  M   backprop, learner's pipe  exp45/e16_life_M_raw65536_cm6_<seed>.json
  Db  windowless two-bank ref.  exp45/e17_life_D_bank2_nbd_cm6_<seed>.json
Memory panels are scored on whole worked answers with no store. Plus-minus = `+-` and `-+` pooled. Twins both-correct =
both_correct / pairs; item accuracy = items_correct / (2 * pairs); the leading control likewise from `lead`.
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
SEEDS = (73129, 93683, 116089)
ARMS = {"Dw": "e16_life_D_cm6_{}.json", "T": "e16_life_T_raw65536_cm6_{}.json", "M": "e16_life_M_raw65536_cm6_{}.json",
        "Db": "e17_life_D_bank2_nbd_cm6_{}.json"}
NAMES = {"Dw": "window reference (backprop, joint stream)", "T": "window learner (sign rule, raw reservoir)",
         "M": "backprop on the learner's pipeline", "Db": "windowless two-bank reference"}
HELD = ("+-", "-+", "><", "<>")
PM = ("+-", "-+")


def load(arm, s):
    p = OUT / ARMS[arm].format(s)
    if not p.exists():
        return None
    j = json.load(open(p))
    return j if j.get("complete") else None


def pm(mem, panel):
    m = mem[panel]
    pairs = sum(m[h]["pairs"] for h in PM)
    both = sum(m[h]["both_correct"] for h in PM); items = sum(m[h]["items_correct"] for h in PM)
    return both, pairs, items, 2 * pairs


def ops(sc, mod):
    return sum(100 * sc[f"{o}{mod}"]["12"]["exact"] / sc[f"{o}{mod}"]["12"]["n"] for o in ("add", "sub", "max", "min")) / 4


def held(sc, key):
    return sum(100 * sc["compose"][h][key] / sc["compose"][h]["n"] for h in HELD) / 4


def main():
    R = {(a, s): load(a, s) for a in ARMS for s in SEEDS}
    L = ["# E20A_TABLES: composition from memory", "",
         "Generated by `e20a_score.py` (reads only). Memory panels (`scores.memory`) are scored on whole worked answers with no store. "
         "Plus-minus = `+-` and `-+` twins pooled (300 twins, 600 items per seed). Counts are given beside percentages.", ""]
    # end-of-life summary
    L += ["## End of life (checkpoint 6), plus-minus pairs pooled", "",
          "| Arm | Seed | Twins both correct (`memory.twins`) | Twin items (`memory.twins`) | Leading control items (`memory.lead`) | Lead − twin (points) | Silenced twins both correct (`memory_silenced.twins`) |",
          "|---|---:|---|---|---|---:|---|"]
    E = {}
    for (a, s), j in R.items():
        if not j:
            continue
        sc = j["stages"][-1]["scores"]
        b, p, it, n = pm(sc["memory"], "twins"); lb, lp, li, ln = pm(sc["memory"], "lead"); sb, sp, _, _ = pm(sc["memory_silenced"], "twins")
        E[a, s] = dict(both=100 * b / p, item=100 * it / n, lead=100 * li / ln)
        L.append(f"| {a} | {s} | {b}/{p} = {100 * b / p:.1f}% | {it}/{n} = {100 * it / n:.1f}% | {li}/{ln} = {100 * li / ln:.1f}% | "
                 f"{100 * li / ln - 100 * it / n:+.1f} | {sb}/{sp} = {100 * sb / sp:.1f}% |")
    # per arm, seed, checkpoint
    for (a, s), j in R.items():
        if not j:
            continue
        L += ["", f"## {a}: {NAMES[a]}, seed {s}", "",
              "Memory panels, whole worked answers, by operator pair: twins both correct / twin items (of 150 / 300) · leading control both / items · silenced twins both.", "",
              "| Ckpt | " + " | ".join(f"`{h}` twins" for h in HELD) + " | " + " | ".join(f"`{h}` lead" for h in HELD) + " | Silenced twins both (`+-` `-+` `><` `<>`) | within_hidden exact / final (of 300) | taught_hidden exact / final (of 300) |",
              "|---:|" + "---|" * 11]
        for st in j["stages"]:
            m, ms = st["scores"]["memory"], st["scores"]["memory_silenced"]
            L.append(f"| {st['stage']} | " + " | ".join(f"{m['twins'][h]['both_correct']} / {m['twins'][h]['items_correct']}" for h in HELD) + " | "
                     + " | ".join(f"{m['lead'][h]['both_correct']} / {m['lead'][h]['items_correct']}" for h in HELD) + " | "
                     + " ".join(str(ms['twins'][h]['both_correct']) for h in HELD) + f" | {m['within_hidden']['exact']} / {m['within_hidden']['final']} | "
                     f"{m['taught_hidden']['exact']} / {m['taught_hidden']['final']} |")
        L += ["", "Registered composition panels (`scores.compose`, standard prompts), whole answer (`exact`) and final answer (`final`), of 600 each; family means at k = 12 (%).", "",
              "| Ckpt | " + " | ".join(f"`{h}` exact / final" for h in HELD + ("within",)) + " | mod-97 ops | held exact | held final | mod-73 ops | CPU updates | CPU scoring |",
              "|---:|" + "---|" * 11]
        for st in j["stages"]:
            sc = st["scores"]
            L.append(f"| {st['stage']} | " + " | ".join(f"{sc['compose'][h]['exact']} / {sc['compose'][h]['final']}" for h in HELD + ("within",))
                     + f" | {ops(sc, 97):.1f} | {held(sc, 'exact'):.1f} | {held(sc, 'final'):.1f} | {ops(sc, 73):.1f} | "
                     f"{st.get('cpu_updates_so_far', 0):.0f} | {st.get('cpu_scoring_so_far', 0):.0f} |")
    # verdicts
    L += ["", "## Verdicts", ""]
    dw = [s for s in SEEDS if ("Dw", s) in E]
    if len(dw) == 3:
        n1 = sum(E["Dw", s]["both"] >= 20 for s in SEEDS)
        L.append(f"- **P20.1** window reference, twins both correct ≥ 20% in ≥ 2 seeds: " + ", ".join(f"{s} {E['Dw', s]['both']:.1f}%" for s in SEEDS)
                 + f" → {n1} of 3 → **{'holds' if n1 >= 2 else 'misses'}**.")
        n2 = sum(E["Dw", s]["lead"] - E["Dw", s]["item"] >= 15 for s in SEEDS)
        L.append(f"- **P20.2** lead − twin item accuracy ≥ 15 points in all three: " + ", ".join(f"{s} {E['Dw', s]['lead'] - E['Dw', s]['item']:+.1f}" for s in SEEDS)
                 + f" → {n2} of 3 → **{'holds' if n2 == 3 else 'misses'}**.")
        n3 = sum(E["Dw", s]["lead"] >= 70 for s in SEEDS)
        L.append(f"- **P20.3** leading control item accuracy ≥ 70% in ≥ 2 seeds: " + ", ".join(f"{s} {E['Dw', s]['lead']:.1f}%" for s in SEEDS)
                 + f" → {n3} of 3 → **{'holds' if n3 >= 2 else 'misses'}**.")
    else:
        L.append("- P20.1–3: window reference not finished on all three seeds.")
    if all(("Db", s) in E for s in SEEDS):
        n4 = sum(E["Db", s]["both"] <= 5 for s in SEEDS)
        L.append(f"- **P20.4** windowless reference twins both correct ≤ 5% in all three: " + ", ".join(f"{s} {E['Db', s]['both']:.1f}%" for s in SEEDS)
                 + f" → **{'holds' if n4 == 3 else 'misses'}**.")
    else:
        L.append("- P20.4: not run (stage 2).")
    for arm, lab, test, thr in (("T", "P20.5", lambda r: r <= .60, "≤ 0.60"), ("M", "P20.6", lambda r: r >= .85, "≥ 0.85")):
        if all((arm, s) in E for s in SEEDS) and len(dw) == 3:
            rs = {s: (E[arm, s]["item"] / E["Dw", s]["item"] if E["Dw", s]["item"] else float("nan")) for s in SEEDS}
            n = sum(test(r) for r in rs.values())
            L.append(f"- **{lab}** {arm} twin item accuracy over the window reference's {thr} in ≥ 2 seeds: " + ", ".join(f"{s} {rs[s]:.2f}" for s in SEEDS)
                     + f" → **{'holds' if n >= 2 else 'misses'}**.")
        else:
            L.append(f"- {lab}: not run (stage 2).")
    (OUT / "E20A_TABLES.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
