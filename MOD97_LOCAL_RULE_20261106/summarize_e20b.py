"""E20-B stage 2 summary: verifies the 24 completion records and weights hashes, and writes the tables, the four verdicts
(P20.7-P20.10) and the amendment-13 selection, read exactly as the operational reading at the end of E20B_PREDICTIONS.md.
Run from MOD97_LOCAL_RULE_20261106. Writes exp45/e20b/E20B_SUMMARY.json and exp45/e20b/E20B_TABLES.md. Reads only; changes no receipt."""
import hashlib
import json
from pathlib import Path

import torch as T

OUT = Path("exp45/e20b")
NETS, SEEDS = ("G0", "G1", "G2", "G3"), (73129, 93683, 116089)
F1 = ("add97", "sub97", "max97", "min97")
F3 = ("add73", "sub73", "max73", "min73")
DEV = ("add89", "sub89", "max89", "min89")
HELD = ("+-", "-+", "><", "<>")
PARAMS_EXPECTED = dict(G0=1125265, G1=1124113, G2=1125873, G3=1158033)


def pct(d):
    return 100.0 * d["exact"] / d["n"]


def pctf(d):
    return 100.0 * d["final"] / d["n"]


def K(sc, n, k):
    d = sc[n]
    return d[str(k)] if str(k) in d else d[k]


def fam(sc, names, k=12):
    return sum(pct(K(sc, n, k)) for n in names) / len(names)


def strict(sc, names):
    return sum(pct(sc["strict_k12"][n]) for n in names) / len(names)


def tensors_sha(sd):
    h = hashlib.sha256()
    for k in sorted(sd):
        v = sd[k].detach().contiguous().cpu()
        h.update(k.encode()); h.update(str(v.dtype).encode()); h.update(str(tuple(v.shape)).encode()); h.update(v.numpy().tobytes())
    return h.hexdigest()


def verify(json_path, pt_path, rec, kind):
    """Completion record present, steps complete, file hash and tensor hash of the weights equal to the record's."""
    c = rec["complete"] if kind == "life" else rec
    file_sha = hashlib.sha256(pt_path.read_bytes()).hexdigest()
    sd = T.load(pt_path, map_location="cpu")
    sd = sd.state_dict() if hasattr(sd, "state_dict") else sd
    t_sha = tensors_sha(sd)
    steps_ok = c["optimizer_steps"] == ([24576] if kind == "birth" else [36864])
    ok = bool(rec.get("complete")) and steps_ok and file_sha == c["weights_sha256"] and t_sha == c["tensors_sha256"]
    if kind == "life":
        ok = ok and len(rec["stages"]) == 7
    return dict(file=json_path.name, weights=pt_path.name, complete=bool(rec.get("complete")), optimizer_steps=c["optimizer_steps"],
                weights_sha256=file_sha, weights_sha256_matches=file_sha == c["weights_sha256"],
                tensors_sha256=t_sha, tensors_sha256_matches=t_sha == c["tensors_sha256"], ok=ok)


def main():
    S = dict(cells={}, verification=[], missing=[])
    lines = ["# E20-B stage 2 tables (generated by `summarize_e20b.py`; whole answers `exact` unless marked final)\n"]
    births, lives = {}, {}
    for n in NETS:
        for s in SEEDS:
            for kind, stem in (("birth", f"e20_dev_{n}_{s}"), ("life", f"e20_life_{n}_{s}")):
                j, p = OUT / f"{stem}.json", OUT / f"{stem}.pt"
                if not j.exists() or not p.exists():
                    S["missing"].append(stem); continue
                rec = json.loads(j.read_text())
                if not rec.get("complete"):
                    S["missing"].append(stem + " (incomplete)"); continue
                S["verification"].append(dict(net=n, seed=s, kind=kind, **verify(j, p, rec, kind)))
                (births if kind == "birth" else lives)[(n, s)] = rec
    S["all_24_verified"] = len(S["verification"]) == 24 and all(v["ok"] for v in S["verification"])

    # parameters and cost
    lines += ["## Parameters and CPU-seconds\n", "| Net | Seed | Params (birth receipt) | Birth CPU-s | Life CPU-s (updates + scoring) | Life scoring CPU-s | Resumes (birth / life) |",
              "|---|---|---:|---:|---:|---:|---|"]
    for (n, s), b in births.items():
        L = lives.get((n, s))
        prm = b["model"]["params"]
        assert prm == PARAMS_EXPECTED[n], (n, prm)
        lc = L["complete"]["cpu_total"] if L else None
        ls = L["complete"].get("cpu_scoring") if L else None
        lr = len(L["stages"][0]["settings"].get("resumes", [])) if L else "-"
        lines.append(f"| {n} | {s} | {prm:,} | {b['cpu_total']:.0f} | {lc:.0f} | {ls:.0f} | {len(b.get('resumes', []))} / {lr} |" if L else
                     f"| {n} | {s} | {prm:,} | {b['cpu_total']:.0f} | - | - | {len(b.get('resumes', []))} / - |")
        S["cells"].setdefault(f"{n}_{s}", {})["params"] = prm
        S["cells"][f"{n}_{s}"]["cpu"] = dict(birth=b["cpu_total"], life=lc, life_scoring=ls)

    # birth curves
    lines += ["\n## Birth curves (sealed mod-89 panels, % exact; k = 0 / 4 / 8 / 12 / 20)\n",
              "| Net | Seed | Step | Loss | add89 | sub89 | max89 | min89 | silenced k=12 add/sub/max/min |", "|---|---|---:|---:|---|---|---|---|---|"]
    for (n, s), b in births.items():
        for row in b["curve"]:
            sl = row["sealed"]
            ks = lambda op: "/".join(f"{pct(K(sl, op, k)):.0f}" for k in (0, 4, 8, 12, 20))
            sil = row.get("silenced_k12") or {}
            sils = "/".join(f"{pct(sil[o]):.0f}" for o in DEV) if sil else "-"
            loss = row.get("loss")
            lines.append(f"| {n} | {s} | {row['step']} | {loss:.4f} | {ks('add89')} | {ks('sub89')} | {ks('max89')} | {ks('min89')} | {sils} |" if isinstance(loss, (int, float))
                         else f"| {n} | {s} | {row['step']} | - | {ks('add89')} | {ks('sub89')} | {ks('max89')} | {ks('min89')} | {sils} |")
        last = b["curve"][-1]["sealed"]
        hard = (pct(K(last, "add89", 12)) + pct(K(last, "sub89", 12))) / 2
        S["cells"][f"{n}_{s}"]["birth_hard_mean_k12"] = hard
        S["cells"][f"{n}_{s}"]["birth_k12"] = {o: K(last, o, 12) for o in DEV}

    # life checkpoints
    lines += ["\n## Life checkpoints (% exact, final answer in brackets for the composition panels)\n",
              "Taught = taught instances (600); within = new instances of taught operator pairs (600); each held pair 600. F1 = mod-97 family mean at k = 12, "
              "F3 = mod-73, dev89 = mod-89; strict = strict-panel means at k = 12.\n",
              "| Net | Seed | Stage | Taught | within | +- | -+ | >< | <> | plus-minus pooled | F1 | F3 | dev89 | strict F1 | strict F3 |",
              "|---|---|---|---|---|---|---|---|---|---:|---:|---:|---:|---:|---:|"]
    for (n, s), L in lives.items():
        rows = []
        for st in L["stages"]:
            sc = st["scores"]; c = sc["compose"]; tg = sc["taught"]
            pm = 100.0 * (c["+-"]["exact"] + c["-+"]["exact"]) / (c["+-"]["n"] + c["-+"]["n"])
            r = dict(stage=st["stage"], task=st["task"] or "birth", taught=pct(tg), taught_final=pctf(tg), within=pct(c["within"]), within_final=pctf(c["within"]),
                     held={h: dict(exact=pct(c[h]), final=pctf(c[h])) for h in HELD}, plus_minus=pm,
                     F1=fam(sc, F1), F3=fam(sc, F3), dev89=fam(sc, DEV), strict_F1=strict(sc, F1), strict_F3=strict(sc, F3))
            rows.append(r)
            lines.append(f"| {n} | {s} | {st['stage']} {r['task']} | {r['taught']:.1f} ({r['taught_final']:.1f}) | {r['within']:.1f} ({r['within_final']:.1f}) | "
                         + " | ".join(f"{r['held'][h]['exact']:.1f} ({r['held'][h]['final']:.1f})" for h in HELD)
                         + f" | {pm:.1f} | {r['F1']:.1f} | {r['F3']:.1f} | {r['dev89']:.1f} | {r['strict_F1']:.1f} | {r['strict_F3']:.1f} |")
        S["cells"][f"{n}_{s}"]["life"] = rows

    # verdicts, as registered
    def end(n, s, key):
        c = S["cells"].get(f"{n}_{s}", {})
        return c["life"][-1][key] if "life" in c and len(c["life"]) == 7 else None

    def hard(n, s):
        return S["cells"].get(f"{n}_{s}", {}).get("birth_hard_mean_k12")

    def count(pred):
        vals = [pred(s) for s in SEEDS]
        return sum(1 for v in vals if v), vals

    V = {}
    for n in ("G1", "G2"):
        V.setdefault("P20.7", {})[n] = [hard(n, s) for s in SEEDS]
    p7 = all(sum(1 for v in V["P20.7"][n] if v is not None and v >= 85) >= 2 for n in ("G1", "G2"))
    V["P20.7"]["holds"] = p7
    V["P20.8"] = {n: [end(n, s, "within") for s in SEEDS] for n in ("G1", "G2")}
    V["P20.8"]["holds"] = any(sum(1 for v in V["P20.8"][n] if v is not None and v >= 85) >= 2 for n in ("G1", "G2"))
    V["P20.9"] = {n: [end(n, s, "plus_minus") for s in SEEDS] for n in ("G1", "G2", "G3")}
    V["P20.9"]["holds"] = any(sum(1 for v in V["P20.9"][n] if v is not None and v >= 40) >= 2 for n in ("G1", "G2", "G3"))
    diffs = [(end("G3", s, "within") - end("G0", s, "within")) if end("G3", s, "within") is not None and end("G0", s, "within") is not None else None for s in SEEDS]
    V["P20.10"] = dict(G3_within=[end("G3", s, "within") for s in SEEDS], G0_within=[end("G0", s, "within") for s in SEEDS], G3_minus_G0=diffs,
                       holds=sum(1 for d in diffs if d is not None and d >= 15) >= 2)
    # amendment 13 selection
    qual = {}
    for n in ("G1", "G2", "G3"):
        seeds = [s for s in SEEDS if end(n, s, "within") is not None and end(n, s, "within") >= 85 and end(n, s, "plus_minus") >= 40]
        qual[n] = dict(seeds=seeds, qualifies=len(seeds) >= 2,
                       plus_minus_mean=(sum(end(n, s, "plus_minus") for s in SEEDS) / 3) if all(end(n, s, "plus_minus") is not None for s in SEEDS) else None)
    if qual["G3"]["qualifies"]:
        cand = "G3"
    elif qual["G1"]["qualifies"] and qual["G2"]["qualifies"]:
        a, b = qual["G1"]["plus_minus_mean"], qual["G2"]["plus_minus_mean"]
        cand = "G2" if b > a else "G1"
    elif qual["G1"]["qualifies"] or qual["G2"]["qualifies"]:
        cand = "G1" if qual["G1"]["qualifies"] else "G2"
    else:
        cand = None
    V["selection_amendment_13"] = dict(qualification=qual, candidate=cand)
    S["verdicts"] = V
    lines += ["\n## Verdicts (as registered; see E20B_REPORT.md)\n", "```", json.dumps(V, indent=1), "```"]
    (OUT / "E20B_SUMMARY.json").write_text(json.dumps(S, indent=1))
    (OUT / "E20B_TABLES.md").write_text("\n".join(lines) + "\n")
    print(json.dumps(dict(verified=len(S["verification"]), all_ok=all(v["ok"] for v in S["verification"]), all_24_verified=S["all_24_verified"],
                          missing=S["missing"], candidate=cand,
                          holds={k: v.get("holds") for k, v in V.items() if isinstance(v, dict) and "holds" in v}), indent=1))


if __name__ == "__main__":
    main()
