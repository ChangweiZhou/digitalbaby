"""E16-M3 tables (read-only): share curves for T and M per seed, per-checkpoint trajectories, and the inputs to P16M3.1-4.
Writes exp45/E16M3_TABLES.md. Works on partial receipts (shows the checkpoints present).

Receipts: T at share s -> e16_life_T_raw65536_drift_online{_rs<pct> unless 0.5}_<seed>.json; M likewise; twin e16_life_D_drift_<seed>.json.
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
F1 = ("add97", "sub97", "max97", "min97")
F3 = ("add73", "sub73", "max73", "min73")
HELD = ("+-", "-+", "><", "<>")
SEEDS = (400009, 600013, 300007)
SHARES = (0.0, 0.25, 0.5, 0.75)


def path(arm, share, seed):
    tag = "" if share == 0.5 else f"_rs{round(100 * share)}"
    return OUT / f"e16_life_{arm}_raw65536_drift_online{tag}_{seed}.json"


def load(p):
    return json.loads(p.read_text())["stages"] if p.exists() else None


def ops(sc, fam):
    return 100 * sum(sc[n]["12"]["exact"] / sc[n]["12"]["n"] for n in fam) / len(fam)


def pr(sc, h):
    c = sc["compose"][h]
    return 100 * c["final"] / c["n"]


def comp(sc):
    return sum(pr(sc, h) for h in HELD) / 4


def hard(sc):
    return (pr(sc, "+-") + pr(sc, "-+")) / 2


def row(sc, tw):
    return dict(f1=ops(sc, F1), hard=hard(sc), comp=comp(sc), f3=ops(sc, F3),
                r1=ops(sc, F1) / ops(tw, F1), rc=comp(sc) / comp(tw), r3=ops(sc, F3) / ops(tw, F3))


def main():
    L = ["# E16-M3 tables: the replay share", "",
         "Generated by `e16m3_tables.py` (read-only). Last checkpoint unless stated. Operations: exact at k = 12, family mean; compositions: final answer; "
         "hard pairs = mean of `+-` and `-+`; ratios to the drift twin (a joint-stream reference). Share 0.5 rows are the comparators already on file "
         "(T: E16-S / E16-F5 / E16-F6 learners; M 400009: E16-M2) except M 600013 at 0.5, which this job ran.", ""]
    res = {}
    for seed in SEEDS:
        tw = load(OUT / f"e16_life_D_drift_{seed}.json")[6]["scores"]
        L += [f"## Seed {seed}", "", f"Twin: mod-97 {ops(tw, F1):.1f}, hard pairs {hard(tw):.1f}, compositions {comp(tw):.1f}, mod-73 {ops(tw, F3):.1f}.", ""]
        for arm in ("T", "M"):
            L += [f"### {arm}: share curve", "", "| share | checkpoints | mod-97 | hard pairs | +- | -+ | comp | ratio mod-97 | ratio comp | ratio mod-73 | mod-73 | CPU s |",
                  "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
            for s in SHARES:
                st = load(path(arm, s, seed))
                if st is None:
                    L.append(f"| {s} | not run | | | | | | | | | | |"); continue
                last = st[-1]["scores"]
                r = row(last, tw)
                if len(st) == 7:
                    res[(arm, seed, s)] = r
                L.append(f"| {s} | {len(st) - 1} | {r['f1']:.1f} | {r['hard']:.1f} | {pr(last, '+-'):.1f} | {pr(last, '-+'):.1f} | {r['comp']:.1f} | "
                         f"{r['r1']:.3f} | {r['rc']:.3f} | {r['r3']:.3f} | {r['f3']:.1f} | {st[-1].get('cpu', 0):.0f} |")
            L.append("")
        L += ["### Trajectories (every checkpoint): mod-97 add / sub / max / min at k = 12 · held pairs +- / -+ / >< / <> (final)", "",
              "| arm | share | ck | add97 | sub97 | max97 | min97 | +- | -+ | >< | <> |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        series = [("D", None, OUT / f"e16_life_D_drift_{seed}.json")] + [(a, s, path(a, s, seed)) for a in ("T", "M") for s in SHARES]
        for a, s, p in series:
            st = load(p)
            if st is None:
                continue
            for i, x in enumerate(st):
                sc = x["scores"]
                L.append(f"| {a} | {'—' if s is None else s} | {i} | " + " | ".join(f"{100 * sc[n]['12']['exact'] / sc[n]['12']['n']:.1f}" for n in F1) + " | "
                         + " | ".join(f"{pr(sc, h):.1f}" for h in HELD) + " |")
        L.append("")
    L += ["## Verdict inputs", ""]
    g = res.get
    for seed in SEEDS:
        t0, t5 = g(("T", seed, 0.0)), g(("T", seed, 0.5))
        if t0 and t5:
            L.append(f"- P16M3.1 {seed}: share 0 mod-97 ratio {t0['r1']:.3f} (< 0.80?), share 0 − share 0.5 mod-97 = {t0['f1'] - t5['f1']:+.1f} (≤ −10?)")
    for seed in (400009, 600013):
        t25, t5, t75 = g(("T", seed, 0.25)), g(("T", seed, 0.5)), g(("T", seed, 0.75))
        if t25 and t5 and t75:
            L.append(f"- P16M3.2 {seed}: hard 0.25 − 0.5 = {t25['hard'] - t5['hard']:+.1f} (≥ +5?), 0.75 − 0.5 = {t75['hard'] - t5['hard']:+.1f} (≤ −5?); "
                     f"mod-97 0.25 − 0.5 = {t25['f1'] - t5['f1']:+.1f} (≤ −3?), 0.75 − 0.5 = {t75['f1'] - t5['f1']:+.1f} (≥ +3?)")
        m5 = g(("M", seed, 0.5))
        for s in (0.25, 0.5, 0.75):
            m = g(("M", seed, s))
            if m and m5:
                L.append(f"- P16M3.3 {seed} M share {s}: comp ratio {m['rc']:.3f} (≥ 0.90?), hard {m['hard']:.1f} vs share-0.5 M {m5['hard']:.1f} (diff {m['hard'] - m5['hard']:+.1f}, |·| ≤ 5?)")
    a, b = g(("T", 300007, 0.25)), g(("T", 300007, 0.75))
    if a and b:
        L.append(f"- P16M3.4 300007: gate at 0.25 {min(a['r1'], a['rc'], a['r3']):.3f}, at 0.75 {min(b['r1'], b['rc'], b['r3']):.3f} (both ≥ 0.80?); hard 0.25 {a['hard']:.1f} vs 0.75 {b['hard']:.1f}")
    text = "\n".join(L) + "\n"
    (OUT / "E16M3_TABLES.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
