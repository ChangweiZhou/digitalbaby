"""E16-RP tables: new (re-keyed, operand-disjoint) composition panels against E16-R3's old panels, and the parity check.

Reads exp45/e16_life_T_raw65536_<seed>.json (new) and exp45/e16_life_T_raw65536_<seed>_oldpanels.json (E16-R3) for the
standing seeds, and writes exp45/SUMMARY_E16RP.md. Reads only. Works on partial receipts (compares the checkpoints both have).
"""
import hashlib
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
SEEDS = (73129, 93683, 116089)
OPS = ("add97", "sub97", "max97", "min97", "add73", "sub73", "max73", "min73", "add89", "sub89", "max89", "min89")
HELD = ("+-", "-+", "><", "<>")


def pct(c):
    return 100 * c["final"] / c["n"]


def main():
    L = ["# SUMMARY_E16RP: held-panel collision measured directly (standing seeds, raw reservoir 65,536)", "",
         "Generated by `e16rp_tables.py`. Old = E16-R3 receipts (`*_oldpanels.json`, held +- triples shared with the taught -> pair). "
         "New = the same life rerun at commit 432e90fb, held and within panels re-keyed and operand-disjoint from every taught triple. "
         "Composition scores are final-answer accuracy in percent; diff = new - old.", ""]
    verdict = {}
    for seed in SEEDS:
        newp, oldp = OUT / f"e16_life_T_raw65536_{seed}.json", OUT / f"e16_life_T_raw65536_{seed}_oldpanels.json"
        if not newp.exists():
            L += [f"## Seed {seed}", "", "new receipt not present", ""]; continue
        new, old = json.loads(newp.read_text())["stages"], json.loads(oldp.read_text())["stages"]
        n = min(len(new), len(old))
        sha = hashlib.sha256((OUT / f"e11_dev_M_{seed}.pt").read_bytes()).hexdigest()
        rec_sha = new[0]["settings"].get("birth_sha256")
        L += [f"## Seed {seed}", "", f"Checkpoints compared: 0–{n - 1} of 0–6. Birth SHA-256 in receipt {'equals' if rec_sha == sha else 'DIFFERS FROM'} the file's (`{sha[:16]}…`).", "",
              "### Parity of operation panels (exact counts, every k, every compared checkpoint)", "",
              "| Panel | ks | identical | first difference |", "|---|---|---|---|"]
        allsame = rec_sha == sha
        for op in OPS:
            diffs = []
            ks = sorted(new[0]["scores"][op].keys(), key=int)
            for i in range(n):
                for k in ks:
                    a, b = new[i]["scores"][op][k], old[i]["scores"][op].get(k)
                    if b is None or a["exact"] != b["exact"] or a["n"] != b["n"]:
                        diffs.append(f"stage {i} k={k}: {a['exact']} vs {None if b is None else b['exact']}")
            allsame &= not diffs
            L.append(f"| {op} | {','.join(ks)} | {'yes' if not diffs else 'NO'} | {diffs[0] if diffs else ''} |")
        sil = [i for i in range(n) for op in new[i]["scores"]["silenced_k12"] if new[i]["scores"]["silenced_k12"][op]["exact"] != old[i]["scores"]["silenced_k12"][op]["exact"]]
        L.append(f"| silenced_k12 (all ops) | 12 | {'yes' if not sil else 'NO'} | {'' if not sil else f'stage {sil[0]}'} |")
        allsame &= not sil
        extra = []
        for i in range(1, n):
            if new[i].get("loss") != old[i].get("loss"):
                extra.append(f"loss stage {i}: {new[i].get('loss')} vs {old[i].get('loss')}")
            for key in ("reservoir_distinct", "reservoir_by_family", "reservoir_bytes", "buffer"):
                if key in old[i] and new[i].get(key) != old[i].get(key):
                    extra.append(f"{key} stage {i}")
        L += ["", f"Extra check (not part of P16RP.1): training loss and reservoir fields {'identical at every compared block' if not extra else 'differ: ' + '; '.join(extra[:4])}.", "",
              "### Held compositions and within, old vs new panels (final answer, %)", "",
              "| Stage | " + " | ".join(f"{h} old | {h} new | {h} diff" for h in HELD) + " | within old | within new | held mean old | held mean new |",
              "|---|" + "---:|" * (3 * len(HELD) + 4)]
        rows = []
        for i in range(n):
            o, w = old[i]["scores"]["compose"], new[i]["scores"]["compose"]
            cells = []
            for h in HELD:
                cells += [f"{pct(o[h]):.1f}", f"{pct(w[h]):.1f}", f"{pct(w[h]) - pct(o[h]):+.1f}"]
            mo, mn = sum(pct(o[h]) for h in HELD) / 4, sum(pct(w[h]) for h in HELD) / 4
            L.append(f"| {i} | " + " | ".join(cells) + f" | {pct(o['within']):.1f} | {pct(w['within']):.1f} | {mo:.1f} | {mn:.1f} |")
            if i >= 4:
                rows.append({h: pct(w[h]) - pct(o[h]) for h in HELD})
        if rows:
            pm = [r["+-"] for r in rows]
            mad = sum(abs(v) for r in rows for v in r.values()) / (4 * len(rows))
            L += ["", f"From block 4 on (stages {', '.join(str(4 + j) for j in range(len(rows)))}): +- diff {', '.join(f'{v:+.1f}' for v in pm)}; max |+- diff| {max(abs(v) for v in pm):.1f} (limit 5); "
                  f"mean |diff| over the four held pairs {mad:.2f} (limit 3)."]
            verdict[seed] = dict(parity=allsame, pm=pm, mad=mad, stages=len(rows))
        else:
            verdict[seed] = dict(parity=allsame)
        L.append("")
    L += ["## Verdict inputs", "", "| Seed | parity (P16RP.1) | +- diffs, stages 4–6 | max abs +- | mean abs diff (4 pairs) |", "|---|---|---|---:|---:|"]
    for s, v in verdict.items():
        pm = v.get("pm")
        L.append(f"| {s} | {'identical' if v['parity'] else 'NOT identical'} | {', '.join(f'{x:+.1f}' for x in pm) if pm else '—'} | "
                 + (f"{max(abs(x) for x in pm):.1f} | {v['mad']:.2f} |" if pm else "— | — |"))
    text = "\n".join(L) + "\n"
    (OUT / "SUMMARY_E16RP.md").write_text(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
