"""E16-F6: the early signature over the twelve drift seeds (reads only).

For each seed with a finished drift learner life (`T_raw65536_drift_online`) and its drift twin (`D_drift`): the learner's
mod-97 family mean at checkpoint 2, its `+-` and `-+` pairs by final answer at checkpoint 6, its ratios to the twin on the
three families at checkpoint 6. Sorted by the first column; Spearman rank correlation (average ranks for ties) between
the checkpoint-2 mod-97 mean and the final `+-`; the two threshold clauses of P16F6.5. Writes exp45/SIGNATURE_E16F6.md.
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "exp45"
SEEDS = (73129, 93683, 116089, 200003, 300007, 400009, 500011, 600013, 700027, 800011, 900007, 1000003)
SOURCE = {73129: "E16-S", 93683: "E16-S", 116089: "E16-S", 200003: "E16-F5", 300007: "E16-F5", 400009: "E16-F5"}
F1 = ("add97", "sub97", "max97", "min97")
F3 = ("add73", "sub73", "max73", "min73")
HELD = ("+-", "-+", "><", "<>")


def op(sc, n):
    return 100 * sc[n]["12"]["exact"] / sc[n]["12"]["n"]


def pair(sc, h):
    c = sc["compose"][h]
    return 100 * c["final"] / c["n"]


def fam(sc):
    return (sum(op(sc, n) for n in F1) / 4, sum(pair(sc, h) for h in HELD) / 4, sum(op(sc, n) for n in F3) / 4)


def load(tag, seed):
    p = OUT / f"e16_life_{tag}_{seed}.json"
    return json.load(open(p))["stages"] if p.exists() else None


def ranks(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    r = [0.0] * len(xs)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for k in range(i, j + 1):
            r[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return r


def spearman(x, y):
    rx, ry = ranks(x), ranks(y)
    mx, my = sum(rx) / len(rx), sum(ry) / len(ry)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    den = (sum((a - mx) ** 2 for a in rx) * sum((b - my) ** 2 for b in ry)) ** 0.5
    return num / den


def main():
    rows, missing = [], []
    for s in SEEDS:
        t, d = load("T_raw65536_drift_online", s), load("D_drift", s)
        if not t or not d or len(t) < 7 or len(d) < 7:
            missing.append(s); continue
        c2 = fam(t[2]["scores"])[0]
        sc, scd = t[6]["scores"], d[6]["scores"]
        ratio = [a / b for a, b in zip(fam(sc), fam(scd))]
        rows.append((c2, s, pair(sc, "+-"), pair(sc, "-+"), ratio))
    rows.sort()
    L = ["# SIGNATURE_E16F6: the early signature over the drift seeds", "",
         "Generated by `e16f6_signature.py` (reads only). Learner `T_raw65536_drift_online`, twin `D_drift`. Checkpoint-2 "
         "mod-97 mean is the family mean at k = 12; `+-` and `-+` are final-answer accuracy (%) at checkpoint 6; ratios "
         "are the learner's family means over the twin's at checkpoint 6 (mod-97 ops · held comp · mod-73 ops).", "",
         "| Seed | Source | Ckpt-2 mod-97 mean | Final `+-` | Final `-+` | Ratios to twin | All three ≥ 0.80 |",
         "|---:|---|---:|---:|---:|---|---|"]
    for c2, s, pm, mp, r in rows:
        L.append(f"| {s} | {SOURCE.get(s, 'E16-F6')} | {c2:.1f} | {pm:.1f} | {mp:.1f} | " + " · ".join(f"{x:.2f}" for x in r)
                 + f" | {'yes' if min(r) >= 0.80 else '**no**'} |")
    L.append("")
    if len(rows) >= 3:
        rho = spearman([r[0] for r in rows], [r[2] for r in rows])
        low = [(s, pm) for c2, s, pm, _, _ in rows if c2 < 70]
        high = [(s, pm) for c2, s, pm, _, _ in rows if c2 > 80]
        L += [f"Seeds: {len(rows)}. Spearman rank correlation, checkpoint-2 mod-97 mean against final `+-`: **{rho:.3f}** "
              f"(clause: at least 0.5).", "",
              f"- Below 70 at checkpoint 2: {', '.join(f'{s} (`+-` {pm:.1f})' for s, pm in low) or 'none'}; "
              f"clause 'every one ends with `+-` below 60': {'holds' if all(pm < 60 for _, pm in low) else 'misses'}.",
              f"- Above 80 at checkpoint 2: {', '.join(f'{s} (`+-` {pm:.1f})' for s, pm in high) or 'none'}; "
              f"clause 'every one ends with `+-` above 65': {'holds' if all(pm > 65 for _, pm in high) else 'misses'}.",
              f"- Between 70 and 80 (no clause): {', '.join(str(s) for c2, s, *_ in rows if 70 <= c2 <= 80) or 'none'}."]
    if missing:
        L += ["", f"Not yet finished (excluded): {', '.join(map(str, missing))}."]
    (OUT / "SIGNATURE_E16F6.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
