"""E34 addendum 2, B050 at 98,304 updates (seed 73129; the user's request of 15 November, after addendum 2's condition: B050's endpoint at the
present length is 17.89 below plain backpropagation's 82.0 at 40 letters). Read-only; trains nothing. A separate script so that
e34_long_read.py, used by the running addendum-2 driver, is not changed.

    python3 e34_long_b050.py read        B050's saved rows present on disk and not yet read -> rows with run "B050" in exp45/e34_long/E34_LONG_READ.json
    python3 e34_long_b050.py hashcheck   B050's row 24,576 against exp45/e34/e34_dev_B050_73129.json
    python3 e34_long_b050.py tables      B050 against B-all by addendum 2's rule; T050 against B050 reported beside -> exp45/e34_long/E34_LONG_B050_TABLES.md

Rule (addendum 2's, for T050 against B-all, applied to B050 against B-all), at 40 letters over the 13 rows 49,152-98,304:
  B050's mean at least 10 above B-all's and above in at least 10 of 13 rows -> "overtakes and stays"; B050's mean not above B-all's ->
  "does not overtake"; otherwise "mixed". T050 against B050: the same quantities, reported; no reading.
"""
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import e34_long_read as L             # noqa: E402  (imports e32_read -> exp20_reference: environment gate)

T, arch26 = L.T, L.arch26
OUT, SEED, DOSE, ROWS, LATE = L.OUT, L.SEED, L.DOSE, L.ROWS, L.LATE
RP = OUT / f"e34_dev_B050_dry{DOSE}_{SEED}.json"
SHORT = HERE / "exp45" / "e34" / "e34_dev_B050_73129.json"
READ = OUT / "E34_LONG_READ.json"


def read():
    arch26.install()
    done = json.loads(READ.read_text()) if READ.exists() else dict(rows=[])
    have = {(r["run"], r["row"], r["sha256"]) for r in done["rows"]}
    files, _ = L.known_rows(RP)
    pk = None
    for row in sorted(files):
        f, want = files[row]
        if ("B050", row, want) in have:
            continue
        pk = pk or L.panels(SEED)
        t0 = time.process_time()
        m, sha = L.load_net(f, want, SEED)
        r = dict(run="B050", seed=SEED, row=row, file=str(f.relative_to(HERE)), sha256=sha, **L.measure(m, SEED, pk))
        r["cpu_s"] = round(time.process_time() - t0, 2)
        done["rows"].append(r)
        READ.write_text(json.dumps(done, indent=1))
        print(f"B050 {row}: acc {r['acc12']:.1f} {r['acc20']:.1f} {r['acc40']:.1f} | keepers {r['keepers12']} {r['keepers20']} {r['keepers40']}", flush=True)
    READ.write_text(json.dumps(done, indent=1))


def hash_check():
    short = json.loads(SHORT.read_text())
    if not RP.exists():
        return {"B050": dict(status="not yet")}
    c = {x["step"]: x for x in json.loads(RP.read_text())["curve"]}
    if 24576 not in c:
        return {"B050": dict(status="not yet")}
    return {"B050": dict(long_row24576=c[24576]["tensors_sha256"], short_final=short["tensors_sha256"],
                         equal=c[24576]["tensors_sha256"] == short["tensors_sha256"], short_receipt=str(SHORT.relative_to(HERE)))}


def compare(rows, a, b):
    x = {r["row"]: r["acc40"] for r in rows if r["run"] == a and r["row"] in LATE}
    y = {r["row"]: r["acc40"] for r in rows if r["run"] == b and r["row"] in LATE}
    assert set(x) == set(y) == set(LATE), f"the 13 late rows of {a} and {b} are not all read"
    mx, my = sum(x.values()) / 13, sum(y.values()) / 13
    return dict(mean_a=mx, mean_b=my, difference=mx - my, rows_a_above=sum(x[r] > y[r] for r in LATE))


def rule(c):
    if c["difference"] >= 10 and c["rows_a_above"] >= 10:
        return "overtakes and stays", "Overtakes and stays, on this seed up to 98,304 updates."
    if not c["mean_a"] > c["mean_b"]:
        return "does not overtake", "Does not overtake up to 98,304 updates on this seed."
    return "mixed", "Mixed; the rows are reported."


def tables():
    rec = json.loads(READ.read_text())
    rows = rec["rows"]
    by = {(r["run"], r["row"]): r for r in rows}
    hc = hash_check()["B050"]
    L_ = ["# E34 addendum 2: B050 at 98,304 updates, seed 73129 (generated by `e34_long_b050.py tables`)", "",
          "## Row-24,576 hash check", "", "| Run | Long run, row 24,576 | Existing final receipt | Equal |", "|---|---|---|---|",
          f"| B050 | {hc.get('long_row24576', '-')} | {hc.get('short_final', '-')} ({hc.get('short_receipt', '')}) | {hc.get('equal', hc.get('status'))} |", "",
          "## Every row (accuracy at 12 / 20 / 40 letters; keepers at 12 / 20 / 40)", "",
          "| Row | B050 acc 12 / 20 / 40 | B-all acc 12 / 20 / 40 | T050 acc 12 / 20 / 40 | B050 keepers | B050 above B-all at 40 | T050 above B050 at 40 |",
          "|---|---|---|---|---|---|---|"]
    f = lambda x: f"{x['acc12']:.2f} / {x['acc20']:.2f} / {x['acc40']:.2f}" if x else "-"  # noqa: E731
    for r in ROWS:
        b5, ba, t5 = by.get(("B050", r)), by.get(("B-all", r)), by.get(("T050", r))
        k = f"{b5['keepers12']} / {b5['keepers20']} / {b5['keepers40']}" if b5 else "-"
        ab1 = ("yes" if b5["acc40"] > ba["acc40"] else "no") if (b5 and ba and r in LATE) else ""
        ab2 = ("yes" if t5["acc40"] > b5["acc40"] else "no") if (t5 and b5 and r in LATE) else ""
        L_.append(f"| {r} | {f(b5)} | {f(ba)} | {f(t5)} | {k} | {ab1} | {ab2} |")
    c1 = compare(rows, "B050", "B-all")
    res, reading = rule(c1)
    c2 = compare(rows, "T050", "B050")
    mean = lambda run, k: sum(by[(run, r)][k] for r in LATE) / 13  # noqa: E731
    L_ += ["", "## The 13 rows 49,152-98,304 (means)", "", "| Run | Mean acc 40 | Mean acc 20 | Mean acc 12 |", "|---|---|---|---|"]
    for run in ("B050", "B-all", "T050"):
        L_.append(f"| {run} | {mean(run, 'acc40'):.2f} | {mean(run, 'acc20'):.2f} | {mean(run, 'acc12'):.2f} |")
    L_ += ["", "## B050 against B-all (addendum 2's rule)", "",
           f"B050 minus B-all (mean at 40 letters): {c1['difference']:+.2f} points; B050 above B-all in {c1['rows_a_above']} of 13 rows.", "",
           f"**Result: {res}.** Reading: {reading}", "",
           "## T050 against B050 (reported beside; no reading)", "",
           f"T050 minus B050 (mean at 40 letters): {c2['difference']:+.2f} points; T050 above B050 in {c2['rows_a_above']} of 13 rows."]
    (OUT / "E34_LONG_B050_TABLES.md").write_text("\n".join(L_) + "\n")
    rec.update(hash_check_row24576_B050=hc, B050_vs_B_all=dict(c1, result=res, reading=reading), T050_vs_B050=c2,
               late_means_B050={k: mean("B050", k) for k in ("acc12", "acc20", "acc40")})
    READ.write_text(json.dumps(rec, indent=1))
    print("\n".join(L_))


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "read":
        read(); sys.exit(0)
    if cmd == "hashcheck":
        print(json.dumps(hash_check())); sys.exit(0)
    if cmd == "tables":
        tables(); sys.exit(0)
    raise SystemExit(__doc__)
