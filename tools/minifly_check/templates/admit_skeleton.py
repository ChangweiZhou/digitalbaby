def run_testbed_learner(config, world, taught_rows, eval_items, checkpoint, gen_cap):
    """Train the evaluator-only ceiling or floor learner `config` (a grid entry with 'id' and
    'learner') on `taught_rows` for `world` within the lock budget, then generate exactly `gen_cap`
    bytes for each item of `eval_items` at `checkpoint` WITHOUT stopping at EOS.

    Returns {item_id: bytes} with len(bytes) == gen_cap for every item."""
    raise NotImplementedError('implement the evaluator-only ceiling/floor learner')


def directional_fixture(port, sign, params):
    """Return {'target_margin_delta_vs_passive': float, 'zero_coef_digest_equals_passive': bool computed
    by comparing digests, 'zero_replay_applications': int counted at the replay site} for one port and
    sign, using exactly the production params."""
    raise NotImplementedError('implement the directional fixture for this port')


def gate_fixture(gate, kind, params):
    """Run plumbing gate `gate` on a constructed negative ('negative') or positive ('positive') input.
    Return the gate's own boolean result, computed by the gate code (never a literal)."""
    raise NotImplementedError('implement the plumbing-gate fixture')


