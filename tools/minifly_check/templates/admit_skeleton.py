def eval_pools(lock):
    split = lock['split']
    pools = {}
    for pool, key in (('HELD', 'held_manifest'), ('OLD', 'old_manifest'), ('NEW', 'new_manifest')):
        rel = split.get(key)
        if rel and os.path.exists(os.path.join(HERE, rel)):
            pools[pool] = load_jsonl(rel)
    return pools


def testbed(lock, attempt_id, only_world, only_arm):
    fmt = lock['task']['format']
    gen_cap = int(fmt['gen_cap_bytes'])
    eos = bytes.fromhex(fmt['eos_hex'])
    worlds = [w for w in lock['worlds']['technical'] if only_world in (None, w)]
    configs = [('CEILING_' + c['id'], c) for c in lock['testbed']['ceiling_grid']]
    configs += [('FLOOR_' + c['id'], c) for c in lock['testbed']['floor_grid']]
    pools = eval_pools(lock)
    taught_dir = lock['split']['taught_manifest']
    out = RowWriter('results/admission/OUTPUTS.jsonl')
    try:
        for world in worlds:
            taught_path = os.path.join(taught_dir, world, 'W.jsonl')
            taught_rows = load_jsonl(taught_path)
            pools_here = dict(pools)
            pools_here['TAUGHT'] = [{'item_id': 't%05d' % i, 'prompt_hex': r['prompt_hex'],
                                     'expected_hex': r['answer_hex']} for i, r in enumerate(taught_rows)]
            for arm, config in configs:
                if only_arm not in (None, arm):
                    continue
                for pool, items in sorted(pools_here.items()):
                    for checkpoint in ('final',):
                        streams = run_testbed_learner(config, world, taught_rows, items, checkpoint, gen_cap)
                        for item in items:
                            stream = streams[item['item_id']]
                            if len(stream) != gen_cap:
                                raise ValueError('stream for %s is %d bytes, not gen_cap %d'
                                                 % (item['item_id'], len(stream), gen_cap))
                            emitted, own_eos = derive_emitted(stream, eos)
                            out.write({
                                'world': world, 'world_role': 'technical', 'arm': arm, 'pool': pool,
                                'checkpoint': checkpoint, 'item_id': item['item_id'],
                                'prompt_hex': item['prompt_hex'], 'expected_hex': item.get('expected_hex'),
                                'stream_hex': stream.hex(), 'emitted_hex': emitted.hex(), 'own_eos': own_eos,
                                'answer_path': 'evaluator', 'native_closure_sha': None, 'params_sha256': None,
                                'attempt_id': attempt_id,
                            })
    finally:
        out.close()


def technical(lock, attempt_id):
    params = load_json(lock['files']['params'])
    fx = RowWriter('results/admission/FIXTURES.jsonl')
    try:
        for port in lock.get('ports') or []:
            for sign in port.get('signs') or []:
                res = directional_fixture(port['id'], sign, params)
                row = {'port': port['id'], 'sign': sign, 'params': params, 'attempt_id': attempt_id}
                row.update(res)
                fx.write(row)
        for gate in lock.get('gates') or []:
            for kind in ('negative', 'positive'):
                fx.write({'gate_id': gate['id'], 'kind': kind, 'params': params,
                          'result': gate_fixture(gate['id'], kind, params), 'attempt_id': attempt_id})
    finally:
        fx.close()
    worlds = list(lock['worlds']['technical'])
    with open(os.path.join(HERE, 'ENDPOINT_LOCK.json'), 'rb') as fh:
        el_sha = hashlib.sha256(fh.read()).hexdigest()
    with open(os.path.join(HERE, 'SOURCE_LOCK.json'), 'rb') as fh:
        sl_sha = hashlib.sha256(fh.read()).hexdigest()
    with open(os.path.abspath(__file__), 'rb') as fh:
        me_sha = hashlib.sha256(fh.read()).hexdigest()
    admission = {
        'schema': 'minifly.admission.v1',
        'endpoint_lock_sha256': el_sha,
        'source_lock_sha256': sl_sha,
        'producer': {'script': 'admit.py', 'sha256': me_sha},
        'worlds': worlds,
        'testbed_outputs': 'results/admission/OUTPUTS.jsonl',
        'receipts_glob': 'results/receipts/*/*.json',
        'fixtures': 'results/admission/FIXTURES.jsonl',
        'input_contrast': measure_input_contrast(params, worlds),
        'structure_meters': measure_structure_meters(params, worlds),
        'parent_admission_sha': None,
        'created_utc': time.strftime('%Y%m%dT%H%M%SZ', time.gmtime()),
    }
    with open(os.path.join(HERE, 'ADMISSION.json'), 'w', encoding='utf-8') as fh:
        fh.write(json.dumps(admission, indent=2, sort_keys=True, allow_nan=False) + '\n')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument('--testbed', action='store_true', help='cycle 0: ceiling and floor grids')
    mode.add_argument('--technical', action='store_true', help='fixtures and ADMISSION.json')
    ap.add_argument('--only-world')
    ap.add_argument('--only-arm')
    args = ap.parse_args(argv)
    attempt_id = os.environ.get('MINIFLY_ATTEMPT_ID')
    if not attempt_id:
        sys.stderr.write('admit.py: MINIFLY_ATTEMPT_ID is unset; run through MFC launch\n')
        return 2
    lock = load_json('ENDPOINT_LOCK.json')
    assets = lock['files'].get('assets') or []
    write_runtime_closure(assets)
    try:
        if args.testbed:
            testbed(lock, attempt_id, args.only_world, args.only_arm)
        else:
            technical(lock, attempt_id)
    finally:
        write_runtime_closure(assets)
    return 0


if __name__ == '__main__':
    sys.exit(main())
