#!/usr/bin/env python3
"""admit.py skeleton for an MRK-1 (schema v1) delivery: the evaluator-side admission script.

Copy this file to <delivery>/admit.py, list it as ENDPOINT_LOCK.files.admit (it is endpoint-locked:
editing it after the lock needs an amendment, AMD-05), and fill in the functions that raise
NotImplementedError. The program checker never imports or runs this file. You run it only through
the launch wrapper, which records the attempt (RUN-01):

    python3 -I tools/minifly_check/minifly_check.py launch --stage testbed <dir> -- python3 -I admit.py --testbed
    python3 -I tools/minifly_check/minifly_check.py score <dir> --role admission
    python3 -I tools/minifly_check/minifly_check.py launch --stage technical <dir> -- python3 -I admit.py --technical

What it writes (field-level schemas: tools/minifly_check/SCHEMAS.md):
- --testbed (cycle 0, before learner code): results/admission/OUTPUTS.jsonl rows for the arms
  CEILING_<id> and FLOOR_<id>, one arm per config of ENDPOINT_LOCK.testbed.ceiling_grid and floor_grid,
  on the exact split, worlds and budget of the lock. Ceiling and floor learners are evaluator-only:
  their rows carry answer_path 'evaluator' and never sit on the native answer path.
- --technical: results/admission/FIXTURES.jsonl (directional fixtures for every lock port and sign,
  plus one negative and one positive fixture per plumbing gate) and ADMISSION.json (input contrast and
  structure meters). Receipts and native OUTPUTS rows come from the runner (run.py), not from here.

Rules this skeleton follows and you must keep:
- stream_hex holds exactly gen_cap_bytes generated bytes, generated without stopping at EOS;
  emitted_hex and own_eos are derived from it (the checker recomputes both, MET-01).
- Every row is written and flushed before any assertion or summary runs.
- It never computes a verdict, a pass/fail flag, a score or a margin: the checker owns scoring,
  the shortcut ladder, strata and the decision rule. It never writes literal integrity booleans
  (LOCK-08).
- attempt_id comes from MINIFLY_ATTEMPT_ID, which only `launch` sets; without it the script refuses.
- --only-world/--only-arm support the reviewer's replay of single histories.
- Every counted run (technical, dev, rehearsal, official) writes its runtime closure (RUN-03):
  write_runtime_closure() lists every repo file in sys.modules plus the declared data assets in
  runlog/RUNTIME_CLOSURE_<attempt_id>.json. Call it right after the imports and again at the very end
  (also on error); copy it into run.py too. The closure is computed from sys.modules, never listed by
  hand; a repo .py file absent from SOURCE_LOCK.closure_sha256 is a closure gap (RUN-03 FAIL).
"""
import argparse
import hashlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))


def load_json(rel):
    with open(os.path.join(HERE, rel), 'rb') as fh:
        return json.loads(fh.read().decode('utf-8'))


def load_jsonl(rel):
    path = os.path.join(HERE, rel)
    rows = []
    with open(path, 'rb') as fh:
        for line in fh:
            line = line.strip()
            if line:
                rows.append(json.loads(line.decode('utf-8')))
    return rows


class RowWriter:
    """Append-and-flush JSONL writer: rows hit the disk before anything else runs."""

    def __init__(self, rel):
        self.path = os.path.join(HERE, rel)
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        self.fh = open(self.path, 'a', encoding='utf-8')

    def write(self, row):
        self.fh.write(json.dumps(row, sort_keys=True, allow_nan=False) + '\n')
        self.fh.flush()
        os.fsync(self.fh.fileno())

    def close(self):
        self.fh.close()


def write_runtime_closure(assets=()):
    """RUN-03 runtime closure: every repo file in sys.modules plus `assets` (delivery-relative files.assets)."""
    root = os.path.realpath(os.environ['MINIFLY_REPO_ROOT'])
    base = os.path.join(root, os.environ['MINIFLY_DELIVERY'])
    paths = {os.path.realpath(m.__file__) for m in list(sys.modules.values()) if getattr(m, '__file__', None)}
    paths |= {os.path.realpath(os.path.join(base, a)) for a in assets}
    files = []
    for p in sorted(x for x in paths if x.startswith(root + os.sep) and os.path.isfile(x)):
        with open(p, 'rb') as fh:
            files.append({'path': os.path.relpath(p, root).replace(os.sep, '/'),
                          'sha256': hashlib.sha256(fh.read()).hexdigest()})
    out = os.path.join(base, os.environ['MINIFLY_RUNTIME_CLOSURE'])
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out + '.tmp', 'w', encoding='utf-8') as fh:
        json.dump({'schema': 'minifly.runtime_closure.v1', 'attempt_id': os.environ['MINIFLY_ATTEMPT_ID'],
                   'files': files}, fh, indent=1, sort_keys=True)
    os.replace(out + '.tmp', out)


def derive_emitted(stream, eos):
    """Bytes before the first EOS within the generation cap, and whether an EOS was emitted."""
    pos = stream.find(eos)
    if pos < 0:
        return stream, False
    return stream[:pos], True


